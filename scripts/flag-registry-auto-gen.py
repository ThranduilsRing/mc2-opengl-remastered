#!/usr/bin/env python3
"""flag-registry-auto-gen.py — generate docs/flags.auto.yaml.

Sources:
  1. RenderCore/RendererFeatureRegistry.h (kFeatureTable + kAuxEnvVars
     EnvVarDesc entries) -> registered flags with kind/default/doc.
  2. getenv("MC2_*") / GetEnvironmentVariable*("MC2_*") sweep across
     mclib/ GameOS/ code/ RenderCore/ editor/ -> usage sites.
Cross-checks:
  - scripts/run_smoke.py quoted "MC2_*" literals (smoke env passthrough).
  - docs/tier1_env_vars.md mentions.

Output is deterministic (sorted, no timestamps): re-running on an
unchanged tree produces byte-identical docs/flags.auto.yaml.

REGISTRY-PARSER-TRUTH-1 (2026-07-31) -- WHY THE PARSE IS NO LONGER LOCAL
------------------------------------------------------------------------
This script's private ENTRY_RE required the doc field to be exactly ONE string
literal immediately followed by `}`.  Measured on HEAD 399b2218f it parsed
248 of the header's 360 rows and exited 0, and its output IS THE TRACKED FILE
docs/flags.auto.yaml -- so the repo carried a committed document asserting
`registered: no` about 73 gates that are registered, including MC2_BOOT_INFO,
MC2_BOOT_OBJ and MC2_LIGHTING_DEBUG_VIEW.  Future sessions read that file as
ground truth.

The 112 dropped rows, by cause:
    99  adjacent string literals in the doc (C concatenation)
     7  a trailing comma after the doc string
     5  both of the above
     1  an inline comment between two fields
All four constructs are legal C++ that a human will keep writing.  The grammar
now lives in scripts/registry_parse.py, tolerates all of them, and REFUSES
(exit 2, nothing written) rather than emitting a plausible partial -- because a
generator that writes a tracked file from a partial parse converts a silent
parser bug into a durable, quotable falsehood.

Usage: py -3 scripts/flag-registry-auto-gen.py [--out PATH]
       py -3 scripts/flag-registry-auto-gen.py --selftest
"""

import argparse
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from registry_parse import (          # noqa: E402
    RegistryParseError,
    parse_registry as _shared_parse_registry,
)

# Bumped from 1.0.0: v1.0.0 output was generated by the 248-of-360 parser, so a
# consumer that trusts the version string can tell the two vintages apart.
GENERATOR_VERSION = "2.0.0"

REPO_ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
REGISTRY_HEADER = os.path.join("RenderCore", "RendererFeatureRegistry.h")
SWEEP_DIRS = ["mclib", "GameOS", "code", "RenderCore", "editor",
              "RenderWorld", "GameAdapters", "EditorBridge", "GuiRuntime",
              "gui", "mission", "netlib"]
SWEEP_EXTS = {".cpp", ".h", ".hpp", ".c", ".cc", ".inl"}
SMOKE_SCRIPT = os.path.join("scripts", "run_smoke.py")
TIER1_DOC = os.path.join("docs", "tier1_env_vars.md")
DEFAULT_OUT = os.path.join("docs", "flags.auto.yaml")

MAX_REFS = 3


def read_text(relpath):
    with open(os.path.join(REPO_ROOT, relpath), "r", encoding="utf-8", errors="replace") as f:
        return f.read()


# ---------------------------------------------------------------------------
# 1. Registry parse
# ---------------------------------------------------------------------------

def parse_registry(header_path=None):
    """Every EnvVarDesc row in the header, in file order.

    Delegates to the shared strict parser.  Raises RegistryParseError (NOT a
    partial list) when the header does not parse cleanly and completely; main()
    turns that into exit 2 with nothing written.

    `header_path` exists so the self-test can point at a CORRUPTED COPY in a temp
    directory.  The self-test must never write the live header: a board run that
    briefly replaces RendererFeatureRegistry.h is exactly the concurrent-write
    window that produced the torn read PACK-FAILLOUD-1 reproduced.
    """
    path = header_path or os.path.join(REPO_ROOT, REGISTRY_HEADER)
    reg = _shared_parse_registry(path)
    return [{
        "feature_id": e["featureId"],
        "env_var": e["envVar"],          # None if nullptr
        "kind": e["kind"],
        "default_on": e["defaultOn"],
        "doc": e["doc"],
        "table": e["table"],
    } for e in reg.values()]


# ---------------------------------------------------------------------------
# 2. getenv sweep
# ---------------------------------------------------------------------------

GETENV_RE = re.compile(
    r'(?:getenv|GetEnvironmentVariable[AW]?|_wgetenv|getenv_s'
    r'|envFlag|envFlagDefaultOn|envFlagOn)\s*\(\s*'
    r'L?"(MC2_[A-Z0-9_]+)"')


def sweep_getenv():
    """Return dict flag -> sorted list of 'relpath:line' reference sites."""
    refs = {}
    for d in SWEEP_DIRS:
        droot = os.path.join(REPO_ROOT, d)
        if not os.path.isdir(droot):
            continue
        for dirpath, dirnames, filenames in os.walk(droot):
            dirnames.sort()
            for fn in sorted(filenames):
                if os.path.splitext(fn)[1].lower() not in SWEEP_EXTS:
                    continue
                full = os.path.join(dirpath, fn)
                rel = os.path.relpath(full, REPO_ROOT).replace("\\", "/")
                try:
                    with open(full, "r", encoding="utf-8", errors="replace") as f:
                        for lineno, line in enumerate(f, 1):
                            for m in GETENV_RE.finditer(line):
                                refs.setdefault(m.group(1), []).append("%s:%d" % (rel, lineno))
                except OSError:
                    continue
    for k in refs:
        refs[k].sort()
    return refs


# ---------------------------------------------------------------------------
# 3. Cross-checks
# ---------------------------------------------------------------------------

def smoke_passthrough_flags():
    text = read_text(SMOKE_SCRIPT)
    return set(re.findall(r'"(MC2_[A-Z0-9_]+)"', text))


def tier1_doc_flags():
    text = read_text(TIER1_DOC)
    return set(re.findall(r'\b(MC2_[A-Z0-9_]+)\b', text))


# ---------------------------------------------------------------------------
# 4. Merge + emit
# ---------------------------------------------------------------------------

def yaml_quote(s):
    """Emit a YAML double-quoted scalar.

    Control characters MUST be escaped, not passed through: the shared parser
    UNESCAPES C string literals (so a `\\n` in the header becomes a real newline
    in `doc`), and a raw newline inside a double-quoted scalar silently turns one
    YAML mapping value into a multi-line fold or a parse error.  The previous
    generator never hit this only because its regex handed back the still-escaped
    source text.
    """
    out = (s.replace("\\", "\\\\").replace('"', '\\"')
            .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t"))
    return '"' + out + '"'


def build_yaml(registry_entries, sweep_refs, smoke_set, tier1_set):
    by_env = {}
    for e in registry_entries:
        if e["env_var"]:
            by_env[e["env_var"]] = e

    all_flags = sorted(set(by_env) | set(sweep_refs))

    lines = []
    lines.append("# AUTO-GENERATED by scripts/flag-registry-auto-gen.py v%s -- DO NOT EDIT BY HAND." % GENERATOR_VERSION)
    lines.append("# Regenerate: py -3 scripts/flag-registry-auto-gen.py")
    lines.append("# Sources: RenderCore/RendererFeatureRegistry.h (registry),")
    lines.append("#          getenv sweep over mclib/ GameOS/ code/ RenderCore/ editor/,")
    lines.append("#          scripts/run_smoke.py passthrough allowlist, docs/tier1_env_vars.md.")
    lines.append("generator_version: %s" % yaml_quote(GENERATOR_VERSION))
    lines.append("registry_entry_count: %d" % len(registry_entries))
    lines.append("registry_env_flag_count: %d" % len(by_env))
    lines.append("sweep_flag_count: %d" % len(sweep_refs))
    lines.append("flag_count: %d" % len(all_flags))
    lines.append("flags:")
    for flag in all_flags:
        reg = by_env.get(flag)
        refs = sweep_refs.get(flag, [])
        lines.append("  - name: %s" % flag)
        if reg is not None:
            lines.append("    default: %s" % ("on" if reg["default_on"] else "off"))
            lines.append("    kind: %s" % reg["kind"])
            lines.append("    feature_id: %s" % reg["feature_id"])
            lines.append("    declared_in: RenderCore/RendererFeatureRegistry.h (%s)" % reg["table"])
            doc = reg["doc"]
            if len(doc) > 200:
                doc = doc[:197] + "..."
            lines.append("    doc: %s" % yaml_quote(doc))
        else:
            lines.append("    default: unknown")
            lines.append("    declared_in: null")
        if refs:
            lines.append("    referenced_at:")
            for r in refs[:MAX_REFS]:
                lines.append("      - %s" % r)
            if len(refs) > MAX_REFS:
                lines.append("    referenced_at_more: %d" % (len(refs) - MAX_REFS))
        else:
            lines.append("    referenced_at: []")
        lines.append("    registered: %s" % ("yes" if reg is not None else "no"))
        lines.append("    in_smoke_passthrough: %s" % ("yes" if flag in smoke_set else "no"))
        lines.append("    documented_in_tier1_env_vars: %s" % ("yes" if flag in tier1_set else "no"))
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# 5. Self-test
# ---------------------------------------------------------------------------

def selftest():
    """Prove this generator REFUSES a registry it cannot parse, and writes nothing.

    The shared parser's own selftest proves the grammar; this proves the thing
    only the GENERATOR can get wrong -- that a refusal turns into exit 2 with the
    previous, true-if-stale file left untouched, rather than a fresh file that
    quietly demotes registered gates to `registered: no`.

    Corruption is injected into a COPY of the REAL header in a temp directory --
    never a hand-written fixture (which drifts from the file it stands for) and
    never the live tree (which would open a concurrent-write window on the very
    file whose torn read started all this).
    """
    import hashlib
    import shutil
    import tempfile

    src = os.path.join(REPO_ROOT, REGISTRY_HEADER)
    with open(src, "rb") as fh:
        src_bytes = fh.read()
    src_sha = hashlib.sha256(src_bytes).hexdigest()
    text = src_bytes.decode("utf-8")

    tmpdir = tempfile.mkdtemp(prefix="mc2_flaggen_")
    out_path = os.path.join(tmpdir, "flags.yaml")
    hdr_copy = os.path.join(tmpdir, "RendererFeatureRegistry.h")
    failures = 0
    try:
        # A pre-existing output that must survive a refusal untouched.
        sentinel = "# PREVIOUS CONTENT -- MUST SURVIVE A REFUSAL\n"
        with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(sentinel)

        # Control: the live header generates and the count reconciles.
        try:
            entries = parse_registry()
        except RegistryParseError as exc:
            print("  FAIL  the LIVE registry was refused: %s" % exc)
            return 1
        print("  OK    live registry parses: %d rows (%d with env vars)"
              % (len(entries), sum(1 for e in entries if e["env_var"])))

        # Refusal: a row the grammar cannot see at all, in a COPY.
        broken = text.replace(
            "static constexpr EnvVarDesc kAuxEnvVars[] = {",
            "static constexpr EnvVarDesc kAuxEnvVars[] = {\n"
            '    { .featureId = "MC2_SELFTEST_HOLE", .envVar = "MC2_SELFTEST_HOLE",\n'
            "      .kind = EnvVarKind::Trace, .defaultOn = false, .doc = \"probe\" },\n", 1)
        if broken == text:
            print("  FAIL  injection changed nothing -- BLIND")
            return 1
        with open(hdr_copy, "w", encoding="utf-8", newline="") as fh:
            fh.write(broken)

        rc = main_generate(out_path, header_path=hdr_copy)
        if rc == 0:
            print("  FAIL  ACCEPTED a registry with an unparseable row (exit 0)")
            failures += 1
        else:
            print("  OK    refused an unparseable row (exit %d)" % rc)

        with open(out_path, encoding="utf-8") as fh:
            after = fh.read()
        if after == sentinel:
            print("  OK    wrote NOTHING on refusal (previous file intact)")
        else:
            print("  FAIL  OVERWROTE the previous file with %d bytes despite "
                  "refusing" % len(after))
            failures += 1

        with open(src, "rb") as fh:
            now_sha = hashlib.sha256(fh.read()).hexdigest()
        if now_sha == src_sha:
            print("  OK    live header never written (sha256 %s)" % src_sha[:16])
        else:
            print("  FAIL  the self-test MUTATED the live header -- repair it")
            failures += 1
    finally:
        shutil.rmtree(tmpdir, ignore_errors=True)

    if failures:
        print("SELF-TEST FAIL: %d arm(s) did not behave" % failures)
        return 1
    print("SELF-TEST PASS: the generator refuses a registry it cannot parse "
          "completely and leaves the previous flags.auto.yaml in place")
    return 0


def warn_if_registry_unlanded():
    """Say so when the working-tree registry differs from HEAD's.

    This generator sweeps the WORKING TREE, and its output is TRACKED. On a
    shared worktree that means a regeneration can publish another lane's
    uncommitted gate rows into a committed document -- which is precisely why
    scripts/check-flag-registry-drift.sh was parked as advisory rather than
    wired. Observed for real on 2026-07-31: a lane had MC2_MECH_LIGHT_FRESHNESS
    added and uncommitted while this lane was regenerating.

    A warning, not a refusal: regenerating alongside your OWN uncommitted
    registry change is legitimate, as long as both land in the same commit.
    scripts/check-flag-registry-truth.py grades the committed doc against HEAD,
    so an unlanded row shows up there as a disagreement until it is committed.
    """
    try:
        r = subprocess.run(["git", "diff", "--quiet", "HEAD", "--", REGISTRY_HEADER],
                           cwd=REPO_ROOT, capture_output=True,
                           stdin=subprocess.DEVNULL, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return
    if r.returncode == 1:
        sys.stderr.write(
            "WARNING: %s differs from HEAD. This generator reads the WORKING\n"
            "  TREE, so the output will describe gate rows that are not committed.\n"
            "  That is fine only if the registry change and this file land in the\n"
            "  SAME commit; otherwise you are publishing another lane's unlanded\n"
            "  work into a tracked document.\n" % REGISTRY_HEADER)


def main_generate(out_path, header_path=None):
    """Generate to out_path. Returns 0 on success, 2 on a refused registry."""
    if header_path is None:
        warn_if_registry_unlanded()
    try:
        registry_entries = parse_registry(header_path)
    except RegistryParseError as exc:
        sys.stderr.write(
            "ERROR: RenderCore/RendererFeatureRegistry.h did not parse cleanly.\n"
            "  %s\n"
            "REFUSING to write %s -- a partial parse here becomes a committed\n"
            "document asserting 'registered: no' about registered gates.\n"
            % (exc, out_path))
        return 2

    sweep_refs = sweep_getenv()
    smoke_set = smoke_passthrough_flags()
    tier1_set = tier1_doc_flags()

    out = build_yaml(registry_entries, sweep_refs, smoke_set, tier1_set)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)

    by_env = {e["env_var"] for e in registry_entries if e["env_var"]}
    unregistered = sorted(set(sweep_refs) - by_env)
    print("registry entries: %d (%d with env vars)" % (len(registry_entries), len(by_env)))
    print("sweep flags:      %d" % len(sweep_refs))
    print("unregistered:     %d" % len(unregistered))
    print("wrote %s" % out_path)
    return 0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO_ROOT, DEFAULT_OUT))
    ap.add_argument("--selftest", action="store_true",
                    help="prove the generator REFUSES a registry it cannot parse "
                         "completely, and writes nothing when it does")
    args = ap.parse_args()

    if args.selftest:
        return selftest()

    # NOTHING is written when the registry refuses. The output is a TRACKED file
    # that other sessions quote as ground truth, so a stale-but-true
    # flags.auto.yaml is strictly better than a fresh one missing rows: the stale
    # one is at least a snapshot of a registry that existed.
    return main_generate(args.out)


if __name__ == "__main__":
    sys.exit(main())
