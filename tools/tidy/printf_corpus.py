#!/usr/bin/env python3
"""printf_corpus - the format corpus that proves a printf -> std::format conversion keeps its bytes.

WHAT: `--add FILES` re-runs the printf_buffers conversion on the BASE version of each file (git show BASE:file) and records every converted call
(old printf format, new std::format string, per-conversion wrapper and `%s` argument class) in tests/unit/printf_corpus.jsonl. `--emit` turns that
file into tests/unit/printf_corpus_gen.inc, one doctest per distinct format pair: it feeds an edge-value table per conversion to snprintf and to
mc2::fmt::to_buf and requires the same bytes and the same length, at full size and truncated to 8 bytes.
WHY: objhash cannot prove a conversion (the output code changes by design). Byte-equality of the formatted text, per conversion, is the property
the conversion must keep, and the corpus checks it for every format string the engine really uses.

  py -3 tools/tidy/printf_corpus.py --add GuiRuntime/GraphicsOptionsWindow_passes.cpp --base HEAD
  py -3 tools/tidy/printf_corpus.py --emit
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import printf_buffers as pb  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import console_child  # noqa: E402

CORPUS = os.path.join(ROOT, "tests", "unit", "printf_corpus.jsonl")
GEN = os.path.join(ROOT, "tests", "unit", "printf_corpus_gen.inc")

# conversion -> (C++ type of the printf argument, edge-table name)
TYPES = {
    ("d", ""): ("int", "I32"), ("d", "l"): ("long", "I32"), ("d", "ll"): ("long long", "I64"),
    ("i", ""): ("int", "I32"), ("i", "l"): ("long", "I32"), ("i", "ll"): ("long long", "I64"),
    ("u", ""): ("unsigned", "U32"), ("u", "l"): ("unsigned long", "U32"), ("u", "ll"): ("unsigned long long", "U64"), ("u", "z"): ("size_t", "U64"),
    ("x", ""): ("unsigned", "U32"), ("x", "l"): ("unsigned long", "U32"), ("x", "ll"): ("unsigned long long", "U64"), ("x", "z"): ("size_t", "U64"),
    ("X", ""): ("unsigned", "U32"), ("X", "l"): ("unsigned long", "U32"), ("X", "ll"): ("unsigned long long", "U64"), ("X", "z"): ("size_t", "U64"),
    ("o", ""): ("unsigned", "U32"), ("o", "l"): ("unsigned long", "U32"), ("o", "ll"): ("unsigned long long", "U64"), ("o", "z"): ("size_t", "U64"),
    ("c", ""): ("int", "CHR"), ("p", ""): ("void*", "PTR"),
}
for _c in "eEfFgG":
    TYPES[(_c, "")] = ("double", "DBL")
    TYPES[(_c, "l")] = ("double", "DBL")


def base_text(path: str, base: str) -> str:
    r = subprocess.run(["git", "-C", ROOT, "show", f"{base}:{path}"], stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                       **console_child.child_kwargs(redirected=True))
    if r.returncode:
        raise SystemExit(f"printf_corpus: cannot read {base}:{path}: {r.stderr.decode('utf-8', 'replace').strip()}")
    return r.stdout.decode("utf-8", errors="surrogateescape")


def load():
    out = []
    if os.path.exists(CORPUS):
        with open(CORPUS, encoding="utf-8") as fh:
            out = [json.loads(ln) for ln in fh if ln.strip()]
    return out


def save(records):
    with open(CORPUS, "w", encoding="utf-8", newline="\n") as fh:
        for r in sorted(records, key=lambda r: (r["old"], r["new"])):
            fh.write(json.dumps(r, sort_keys=True) + "\n")


def add(files, base: str):
    recs = {(r["old"], r["new"]): r for r in load()}
    added = 0
    for f in files:
        _new, records, _left = pb.convert(base_text(f, base))
        for r in records:
            key = (r["old"], r["new"])
            specs = [{k: s[k] for k in ("conv", "length", "wrap", "cls")} for s in r["specs"]]
            if key not in recs:
                recs[key] = {"old": r["old"], "new": r["new"], "specs": specs, "files": [f]}
                added += 1
            elif f not in recs[key]["files"]:
                recs[key]["files"].append(f)
    save(list(recs.values()))
    return added


def cpp_string(s: str) -> str:
    """A C++ string literal whose contents are `s` (already source-escaped text)."""
    return '"' + s + '"'


def emit(records) -> str:
    lines = ["// GENERATED by tools/tidy/printf_corpus.py from tests/unit/printf_corpus.jsonl -- do not edit.",
             "// One test per distinct (printf format, std::format string) pair of the converted call sites.", ""]
    for n, r in enumerate(sorted(records, key=lambda r: (r["old"], r["new"]))):
        decls, old_args, new_args = [], [], []
        classes = []
        for i, s in enumerate(r["specs"]):
            conv, length, wrap, cls = s["conv"], s["length"], s["wrap"], s["cls"]
            if conv == "s":
                if cls == "literal":
                    old_args.append('"lit"')
                    new_args.append('"lit"')
                else:
                    table = "kStrNull" if cls == "maybe-null" else "kStrNonNull"
                    decls.append(f"const char* v{i} = {table}[(row + {i}) % std::size({table})];")
                    old_args.append(f"v{i}")           # the CRT itself prints (null) for a null %s: that is the behaviour to match
                    new_args.append(f"mc2::fmt::safe(v{i})" if wrap == "safe" else f"v{i}")
                classes.append(cls)
                continue
            ctype, table = TYPES[(conv, length)]
            decls.append(f"{ctype} v{i} = static_cast<{ctype}>(kEdge{table}[(row + {i}) % std::size(kEdge{table})]);" if table != "PTR" else
                         f"void* v{i} = kEdgePTR[(row + {i}) % std::size(kEdgePTR)];")
            old_args.append(f"v{i}")
            new_args.append(f"mc2::fmt::{wrap}(v{i})" if wrap else f"v{i}")
        old_call = ", ".join([cpp_string(r["old"])] + old_args)
        new_call = ", ".join([cpp_string(r["new"])] + new_args)
        title = r["old"].replace("\\", "\\\\").replace('"', "'")[:70]
        note = (" [%s]" % ",".join(sorted(set(classes)))) if classes else ""
        lines += [
            f'TEST_CASE("printf corpus {n:04d}: {title}{note}")',
            "{",
            "\tfor (int row = 0; row < 12; ++row) {",
            *[f"\t\t{d}" for d in decls],
            "\t\tchar a[160], b[160], c[8], d[8];",
            f"\t\tconst int na = std::snprintf(a, sizeof a, {old_call});",
            f"\t\tconst int nb = mc2::fmt::to_buf(b, {new_call});",
            "\t\tCHECK(na == nb);",
            "\t\tCHECK(std::strcmp(a, b) == 0);",
            f"\t\tconst int nc = std::snprintf(c, sizeof c, {old_call});",
            f"\t\tconst int nd = mc2::fmt::to_buf(d, {new_call});",
            "\t\tCHECK(nc == nd);",
            "\t\tCHECK(std::strcmp(c, d) == 0);",
            "\t}",
            "}",
            "",
        ]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--add", nargs="+", metavar="FILE", help="record the conversions of these files (relative to the repo root)")
    ap.add_argument("--base", default="HEAD", help="the revision holding the pre-conversion text of --add files (default HEAD)")
    ap.add_argument("--emit", action="store_true", help="regenerate tests/unit/printf_corpus_gen.inc from the jsonl")
    args = ap.parse_args(argv)
    if args.add:
        print(f"printf_corpus: {add(args.add, args.base)} new format pair(s) recorded")
    if args.emit or args.add:
        recs = load()
        with open(GEN, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(emit(recs))
        print(f"printf_corpus: wrote {os.path.relpath(GEN, ROOT)} ({len(recs)} test case(s))")
    return 0


if __name__ == "__main__":
    sys.exit(main())
