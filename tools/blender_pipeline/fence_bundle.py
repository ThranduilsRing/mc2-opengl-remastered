#!/usr/bin/env python3
"""
fence_bundle.py - build + validate the procedural chain-link fence override bundle.

Drives the existing pipeline (ase_to_glb extract -> blender_pipeline batch_driver
recipe `fence_gen` -> glb_only inject), then assembles a mod-style bundle:

  <out>/data/model_overrides/models.json         engine schema {"overrides":[...]}
  <out>/data/model_overrides/fence/<name>.glb    source paths are manifestDir-relative
  <out>/data/tgl/128/<texture>.tga               engine loads textures from data/tgl/<size>/

Then validates against the rules mclib/model_override_registry.cpp enforces
(type/renderOnly/fallback/scale/safe-source) plus GLB sanity (TEXCOORD_0, bounds
vs the stock-derived GLB, tri budget, texture URIs resolvable in the bundle).

  py -3 tools/blender_pipeline/fence_bundle.py --out G:/mc2-assets/out/fence-procedural
  py -3 tools/blender_pipeline/fence_bundle.py --out ... --validate-only
"""
import argparse
import json
import os
import shutil
import struct
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import batch_driver  # noqa: E402
sys.path.insert(0, str(HERE.parent.parent / "scripts"))
import console_child  # noqa: E402

TRI_BUDGET = 300
BOUNDS_TOL = 1.5   # world units vs stock footprint (posts extend half a post radius)

# appearance name -> (stock ase stem, generated variant, output glb stem)
JOBS = {
    "wirefence":     ("wirefence", "wirefence", "wirefence_proc"),
    "wirefencediag": ("wirefencediag", "wirefencediag", "wirefencediag_proc"),
}
LATTICE = "a_wirefence_proc"
METAL = "fence_metal_proc"


def default_srcdata():
    for c in ("A:/Games/mc2-srcdata/tgl", "A:/Games/mc2-opengl/mc2srcdata-fresh/tgl"):
        if Path(c, "wirefence.ase").is_file():
            return Path(c)
    raise SystemExit("stock srcdata tgl dir not found; pass --srcdata")


def glb_json(path):
    d = Path(path).read_bytes()
    jl = struct.unpack("<I", d[12:16])[0]
    return json.loads(d[20:20 + jl])


def glb_stats(path):
    g = glb_json(path)
    tris = 0
    mn = [1e9] * 3
    mx = [-1e9] * 3
    for m in g["meshes"]:
        for p in m["primitives"]:
            if "TEXCOORD_0" not in p["attributes"]:
                raise ValueError(f"{path}: primitive without TEXCOORD_0")
            tris += g["accessors"][p["indices"]]["count"] // 3
            a = g["accessors"][p["attributes"]["POSITION"]]
            for i in range(3):
                mn[i] = min(mn[i], a["min"][i])
                mx[i] = max(mx[i], a["max"][i])
    return {"tris": tris, "min": mn, "max": mx, "images": [i.get("uri") for i in g.get("images", [])]}


def build(out, srcdata, work, blender=None):
    work.mkdir(parents=True, exist_ok=True)
    jobs = []
    for app, (stem, variant, glb_stem) in JOBS.items():
        jobs.append({
            "name": app, "asset_class": "prop", "recipe": "fence_gen",
            "source": {"ase": str(srcdata / f"{stem}.ase"), "ini": str(srcdata / f"{stem}.ini")},
            "params": {"variant": variant, "lattice": LATTICE, "metal": METAL, "tex_res": 512},
            "out": {"kind": "glb_only", "dir": str(work / "glb"), "source_name": glb_stem},
        })
    manifest = {"schema_version": "1.0", "work_dir": str(work / "_work"), "jobs": jobs}
    mpath = work / "fence_manifest.json"
    mpath.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    argv = [str(mpath)] + (["--blender", blender] if blender else [])
    rc = batch_driver.main(argv)
    if rc != 0:
        raise SystemExit(f"batch_driver failed rc={rc}")

    mo = out / "data" / "model_overrides"
    (mo / "fence").mkdir(parents=True, exist_ok=True)
    tex = out / "data" / "tgl" / "128"
    tex.mkdir(parents=True, exist_ok=True)
    overrides = []
    for app, (_, _, glb_stem) in JOBS.items():
        shutil.copyfile(work / "glb" / f"{glb_stem}.glb", mo / "fence" / f"{glb_stem}.glb")
        overrides.append({
            "type": "model", "replaces": f"staticProp:{app}",
            "source": f"fence/{glb_stem}.glb",
            "scale": 1.0, "renderOnly": True, "fallback": "stock",
        })
    first = next(iter(JOBS))
    for t in (work / "_work" / first / "tex").glob("*.tga"):
        shutil.copyfile(t, tex / t.name)
    (mo / "models.json").write_text(json.dumps({"overrides": overrides}, indent=2) + "\n", encoding="utf-8")
    (out / "LICENSE-NOTES.txt").write_text(
        "Procedurally generated by tools/blender_pipeline/recipes/fence_gen.py.\n"
        "No third-party assets. Project license applies.\n", encoding="utf-8")


def validate(out, srcdata, stock_glb_dir):
    errs = []
    mo = out / "data" / "model_overrides"
    root = json.loads((mo / "models.json").read_text(encoding="utf-8"))
    if not isinstance(root, dict) or not isinstance(root.get("overrides"), list):
        errs.append("models.json: missing 'overrides' array (engine drops bare lists)")
        return errs
    seen = set()
    for e in root["overrides"]:
        key = e.get("replaces", "<none>")
        if e.get("type") != "model": errs.append(f"{key}: type!=model")
        if e.get("renderOnly") is not True: errs.append(f"{key}: renderOnly!=true")
        if e.get("fallback") != "stock": errs.append(f"{key}: fallback!=stock")
        if float(e.get("scale", 1.0)) != 1.0: errs.append(f"{key}: scale!=1.0")
        cls, _, name = key.partition(":")
        if cls.lower() not in ("staticprop", "tree") or not name: errs.append(f"{key}: bad replaces")
        if key.lower() in seen: errs.append(f"{key}: duplicate")
        seen.add(key.lower())
        src = e.get("source", "")
        if (not src.lower().endswith((".glb", ".gltf")) or src.startswith("/") or ".." in src
                or ":" in src):
            errs.append(f"{key}: unsafe source {src!r}")
            continue
        glb = mo / src
        if not glb.is_file():
            errs.append(f"{key}: source missing {glb}")
            continue
        st = glb_stats(glb)
        # ASE y -> Stuff z is positive. Size-only checks miss a reversed run,
        # which looks continuous in a straight line but overshoots every turn.
        import math
        pitch = 128.0 / 3 * (math.sqrt(2) if name == "wirefencediag" else 1.0)
        if abs(st["min"][2] + 0.6325) > 0.01 or abs(st["max"][2] - pitch - 0.6325) > 0.01:
            errs.append(f"{key}: endpoints must be at positive stock run 0..{pitch:.6f}")
        if st["tris"] > TRI_BUDGET: errs.append(f"{key}: {st['tris']} tris > {TRI_BUDGET}")
        for uri in st["images"]:
            if not (out / "data" / "tgl" / "128" / uri).is_file():
                errs.append(f"{key}: texture {uri} not in bundle data/tgl/128")
        ref = stock_glb_dir / f"stock_{name}.glb"
        if ref.is_file():
            # stock-converter GLB is ASE-ish (x thick, y run, z height); the engine frame is
            # glb=(-x,-height,run). Compare SIZES + base height, not the run offset.
            r = glb_stats(ref)
            rs = [r["max"][i] - r["min"][i] for i in range(3)]       # thick, run, height
            ns = [st["max"][i] - st["min"][i] for i in range(3)]     # new glb: thick, height, run
            for label, a, b in (("run", ns[2], rs[1]), ("height", ns[1], rs[2])):
                if abs(a - b) > BOUNDS_TOL:
                    errs.append(f"{key}: {label} extent {a:.2f} vs stock {b:.2f}")
            if abs(-st["max"][1] - r["min"][2]) > BOUNDS_TOL:
                errs.append(f"{key}: base height {-st['max'][1]:.2f} vs stock {r['min'][2]:.2f}")
        print(f"[validate] {key}: {st['tris']} tris, bounds {st['min']} .. {st['max']}, textures {st['images']}")
    return errs


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--out", required=True)
    ap.add_argument("--srcdata")
    ap.add_argument("--blender")
    ap.add_argument("--validate-only", action="store_true")
    a = ap.parse_args(argv)
    out = Path(a.out)
    srcdata = Path(a.srcdata) if a.srcdata else default_srcdata()
    work = out / "_work"
    if not a.validate_only:
        build(out, srcdata, work, a.blender)
    # stock-derived reference GLBs (same extractor the pipeline uses)
    ref_dir = work / "stock_ref"
    ref_dir.mkdir(parents=True, exist_ok=True)
    for app, (stem, _, _) in JOBS.items():
        dst = ref_dir / f"stock_{app}.glb"
        if not dst.is_file():
            subprocess.run([sys.executable, str(HERE.parent / "ase_to_glb.py"),
                            "--ase", str(srcdata / f"{stem}.ase"), "--ini", str(srcdata / f"{stem}.ini"),
                            "--out-glb", str(dst), "--out-sidecar", str(ref_dir / f"stock_{app}.json"),
                            "--asset-class", "prop"], check=True, capture_output=True,
                           **console_child.child_kwargs(redirected=True))
    errs = validate(out, srcdata, ref_dir)
    for e in errs:
        print("[validate] FAIL", e)
    print("[validate]", "OK" if not errs else f"{len(errs)} problem(s)")
    return 1 if errs else 0


if __name__ == "__main__":
    sys.exit(main())
