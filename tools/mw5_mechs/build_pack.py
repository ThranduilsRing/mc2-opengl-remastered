#!/usr/bin/env python3
"""Build the personal-use MW5 Mad Cat appearance pack (a mod) from the owner's own extracted files.

Same shape as tools/bt2018_mechs/build_pack.py: the GLB, BC7 maps and sidecar are COPIED into <install>/mods/<mod-id>/;
nothing in the install's base data is modified. The pack overrides the stock Mad Cat appearance INI
(data/tgl/madcat.ini) so the stock chassis shows the MW5 Timber Wolf model. Never commit the generated pack.

  py -3 tools/mw5_mechs/build_pack.py --install <lane-install> --glb mw5_madcat.glb --textures <cooked data/tgl>
Mount with MC2_MOD_DEPS=mw5_mechs.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_glb import NODE_MAP  # noqa: E402

STEM = "mw5_madcat"
KEEP = ("Gestures", "Bounds", "SmokeNode0", "JumpJetNode0", "FootNode0", "FootNode1", "FootPrint")


def blocks(text):
    cur, body, out = None, [], []
    for raw in text.splitlines():
        s = raw.strip()
        if s.startswith("[") and s.endswith("]"):
            if cur is not None:
                out.append((cur, body))
            cur, body = s[1:-1], []
        elif cur is not None and s and not s.startswith("//") and s.lower() != "fitend":
            body.append(s)
    if cur is not None:
        out.append((cur, body))
    return out


def emit_ini(host_text, weapon_nodes=("weapon_rightarm", "weapon_leftarm", "weapon_righttorso", "weapon_centertorso", "weapon_lefttorso"),
             types=(5, 5, 1, 2, 1)):
    out = ["FITini", "", "// MW5 Timber Wolf appearance for the stock Mad Cat -- generated by tools/mw5_mechs/build_pack.py.",
           "", "[Import]", f'st Source = "{STEM}"', 'st AnimHost = "madcat"', "",
           "[TGLData]", f'st FileName0 = "{STEM}"', "f Distance0 = 0.0", "",
           "[Nodes]", "l NumSmoke = 1", "l NumJumpJet = 1", f"l NumWeapon = {len(weapon_nodes)}", "l NumFeet = 2", ""]
    for i, (n, t) in enumerate(zip(weapon_nodes, types)):
        out += [f"[WeaponNode{i}]", f'st WeaponNodeName = "{n}"', f"l WeaponType = {t}", ""]
    for name, body in blocks(host_text):
        if name.startswith(KEEP):
            out += [f"[{name}]"] + body + [""]
    return "\n".join(out + ["FITend", ""])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--install", required=True)
    ap.add_argument("--glb", required=True)
    ap.add_argument("--textures", required=True, help="directory cooked by cook_textures.py")
    ap.add_argument("--mod-id", default="mw5_mechs")
    a = ap.parse_args()
    inst = Path(a.install)
    host = inst / "data" / "tgl" / "madcat.ini"
    if not host.is_file():
        sys.exit(f"stock madcat.ini not found as a loose file: {host}")
    out = inst / "mods" / a.mod_id
    tgl = out / "data" / "tgl"
    tgl.mkdir(parents=True, exist_ok=True)
    (tgl / "madcat.ini").write_bytes(emit_ini(host.read_text(encoding="latin-1")).encode("latin-1"))
    shutil.copyfile(a.glb, tgl / f"{STEM}.glb")
    for tier in ("", "128"):
        (tgl / tier).mkdir(exist_ok=True)
        for tag in ("alb", "nrm"):
            name = f"{STEM}_{tag}.ktx2"
            src, dst = Path(a.textures) / tier / name, tgl / tier / name
            if src.resolve() != dst.resolve():
                shutil.copyfile(src, dst)
    materials = {kind: {"tga": f"{STEM}_{tag}.tga", "ktx2": f"{STEM}_{tag}.ktx2",
                        "logicalFormat": fmt, "container": "bc7"}
                 for kind, tag, fmt in (("albedo", "alb", "srgb-rgb"), ("normal", "nrm", "linear-normal-xyz"))}
    materials["normal"].update(source="dump:Texture2D/Timberwolf_Body_NRM.png", skinIndependent=True)
    pkg = {"schema": "bt2018-mech-package/2", "chassisId": "mw5:timberwolf", "sourceGlb": f"{STEM}.glb", "nodes": NODE_MAP,
           "materials": materials, "featureBits": ["HAS_NORMAL"]}
    (tgl / f"{STEM}.package.json").write_text(json.dumps(pkg, indent=2) + "\n")
    (out / "mod.json").write_text(json.dumps({
        "schema": "mc2-mod/1", "id": a.mod_id, "name": "MechWarrior 5 Mad Cat (personal use)", "version": "0.1.0",
        "author": "generated by tools/mw5_mechs/build_pack.py", "type": "assets", "dependencies": [],
        "capabilities": ["imported_mechs", "package_chassis"],
        "description": "MW5 Timber Wolf model on the stock Mad Cat, generated from the owner's own MW5 files. Add-on layer: MC2_MOD_DEPS=mw5_mechs. Not for redistribution."}, indent=2) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
