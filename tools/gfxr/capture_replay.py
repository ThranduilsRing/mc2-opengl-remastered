#!/usr/bin/env python3
"""GFXReconstruct capture / replay / A-B on the rented Linux box (RTX 3060, ratio-only; see tools/gfxr/README.md).

    py -3 tools/gfxr/capture_replay.py capture --tag base --mission mc2_10 --bookmarks mc2_10_camera --pose wolfman
    py -3 tools/gfxr/capture_replay.py replay  --tag base -n 7
    py -3 tools/gfxr/capture_replay.py ab --a base --b candidate -n 7

capture: box_run sh row under the current worktree's HEAD build: run_visual_capture.py (the off-screen harness, never mc2 directly)
         with the GFXReconstruct layer enabled; keeps /workspace/gfxr/<tag>/cap.gfxr ON THE BOX (a capture is hundreds of MB).
replay : gfxrecon-replay N times with --measurement-frame-range + --flush-measurement-range; median and IQR of ms/frame.
ab     : two captures (taken from two builds at the same pose, one per tag) replayed N times each, interleaved A,B,A,B,... in ONE
         box job so both see the same GPU/clock state. Replaying one capture on two driver/engine builds is NOT an A/B.
Replay timing is a guide. RGP on the PC 7900 XTX stays the proof for GPU work.
"""
import argparse, re, statistics, subprocess, sys, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import console_child  # noqa: E402

KEY = "C:/SPB_Data/.ssh/mc2farm_ed25519"
HOST, PORT = "root@14.227.95.149", "30598"
GFXR = "/workspace/toolchains/gfxr-1.4.350.0"      # pinned: LunarG Vulkan SDK 1.4.350.0 linux tarball, GFXReconstruct 1.0.5
GDIR = "/workspace/gfxr"

CAPTURE_SH = r'''#!/bin/bash
# generated by tools/gfxr/capture_replay.py; runs under box_run (cwd = lane src, $INSTALL set, xvfb + GPU pin exported)
D=@GDIR@/@TAG@; rm -rf $D; mkdir -p $D
export VK_LAYER_PATH=@GFXR@/share/vulkan/explicit_layer.d VK_INSTANCE_LAYERS=VK_LAYER_LUNARG_gfxreconstruct
export GFXRECON_CAPTURE_FILE=$D/cap.gfxr GFXRECON_CAPTURE_FILE_TIMESTAMP=false GFXRECON_CAPTURE_FRAMES=@FRAMES@
export GFXRECON_LOG_FILE=$D/capture.log GFXRECON_LOG_LEVEL=info
# the harness needs >=2 poses (single-pose sweeps drop the capture): write a 2-pose file, the chosen pose twice
python3 -c "import json,sys;d=json.load(open('tests/visual/bookmarks/@BOOKMARKS@.json'));b=[x for x in d['bookmarks'] if x['name']=='@POSE@'][0];c=dict(b,name='@POSE@_2');d['bookmarks']=[b,c];json.dump(d,open('$D/pose.json','w'))" || exit 8
python3 scripts/run_visual_capture.py --mission @MISSION@ --bookmarks $D/pose.json --exe $INSTALL/mc2 \
  --classic-assets --out-dir $OUT/cap --trigger-frame @TRIGGER@ --no-kill
rc=$?
echo "GFXR_CAPTURE rc=$rc tag=@TAG@ sha=$(git rev-parse --short=8 HEAD) frames=@FRAMES@"
ls -l $D; tail -n 6 $D/capture.log
[ -s $D/cap.gfxr ] || { echo "GFXR_CAPTURE no capture file written"; exit 9; }
$GFXR_BIN/gfxrecon-info $D/cap.gfxr 2>&1 | head -30
exit $rc
'''

REPLAY_SH = r'''#!/bin/bash
# generated by tools/gfxr/capture_replay.py; interleaves the tags N times
B=@GFXR@/bin
export VK_LAYER_PATH=@GFXR@/share/vulkan/explicit_layer.d
nvidia-smi --query-gpu=name,clocks.gr,clocks.mem,temperature.gpu --format=csv,noheader -i ${GPU_IDX:-0} | sed 's/^/GFXR_GPU /'
for i in $(seq 1 @N@); do
  for t in @TAGS@; do
    f=@GDIR@/$t/cap.gfxr; m=$OUT/measure_${t}_$i.json
    $B/gfxrecon-replay --measurement-file $m --flush-measurement-range --log-level warning @EXTRA@ $f > $OUT/replay_${t}_$i.log 2>&1
    echo "GFXR_RUN tag=$t run=$i rc=$? file=$(basename $m)"
    cat $m 2>/dev/null | tr -d '\n ' | cut -c1-400; echo
  done
done
'''


def sh(*a, **k):
    return subprocess.run(*a, capture_output=True, text=True, **console_child.child_kwargs(redirected=True), **k)


def ssh_args():
    return ["ssh", "-i", KEY, "-p", PORT, "-o", "LogLevel=ERROR", HOST]


def push_script(name, text):
    """scp a generated job script to the box; its name stays short because box_run names the row log after the row text."""
    with tempfile.TemporaryDirectory(dir=Path(tempfile.gettempdir())) as td:
        p = Path(td) / name
        p.write_text(text, newline="\n")
        r = sh(["scp", "-q", "-i", KEY, "-P", PORT, str(p), f"{HOST}:{GDIR}/{name}"])
    if r.returncode:
        sh([*ssh_args(), f"mkdir -p {GDIR}"])
        with tempfile.TemporaryDirectory(dir=Path(tempfile.gettempdir())) as td:
            p = Path(td) / name
            p.write_text(text, newline="\n")
            r = sh(["scp", "-q", "-i", KEY, "-P", PORT, str(p), f"{HOST}:{GDIR}/{name}"])
    if r.returncode:
        sys.exit("scp failed: " + r.stderr)


def box_row(job, gpu, repo):
    cmd = [sys.executable, str(ROOT / "tools" / "box_run.py"), "--repo", str(repo), "--gpu", gpu, "--", f"sh:bash {GDIR}/{job}"]
    r = sh(cmd)
    out = r.stdout + r.stderr
    print(out[-3000:])
    m = re.search(r"reports=(\S+)", out)
    return r.returncode, (Path(m.group(1)) if m else None)


def fill(t, **kv):
    for k, v in kv.items():
        t = t.replace("@%s@" % k.upper(), str(v))
    return t


def cmd_capture(a):
    frames = f"{a.start}-{a.start + a.frames - 1}"
    text = fill(CAPTURE_SH, gdir=GDIR, gfxr=GFXR, tag=a.tag, frames=frames, mission=a.mission, bookmarks=a.bookmarks, pose=a.pose,
                trigger=a.trigger_frame).replace("$GFXR_BIN", GFXR + "/bin")
    # one bookmark file may hold many poses; the harness sweeps them all, so the pose is chosen by a one-pose file when given
    push_script(f"cap_{a.tag}.sh", text)
    rc, _ = box_row(f"cap_{a.tag}.sh", "0", a.repo)   # presenting rows run on GPU 0 only (box-game-runs.md)
    return rc


def cmd_replay(a, tags=None):
    tags = tags or [a.tag]
    extra = a.extra or ""
    text = fill(REPLAY_SH, gdir=GDIR, gfxr=GFXR, n=a.n, tags=" ".join(tags), extra=extra)
    name = f"rep_{'_'.join(tags)}.sh"
    push_script(name, text)
    rc, out = box_row(name, a.gpu, a.repo)
    if out is None:
        return rc, {}
    return rc, collect(out, tags)


def collect(out, tags):
    res = {t: [] for t in tags}
    for t in tags:
        for f in sorted(out.rglob(f"measure_{t}_*.json")):
            txt = f.read_text(errors="replace")
            ms = frame_ms(txt)
            if ms is not None:
                res[t].append(ms)
    return res


def frame_ms(txt):
    """ms per frame from a gfxrecon measurement file (JSON; fps / frame_count / duration keys vary by version)."""
    import json
    try:
        d = json.loads(txt)
    except ValueError:
        return None
    flat = {}

    def walk(o):
        if isinstance(o, dict):
            for k, v in o.items():
                if isinstance(v, (dict, list)):
                    walk(v)
                else:
                    flat[k.lower()] = v
        elif isinstance(o, list):
            for v in o:
                walk(v)
    walk(d)
    if "fps" in flat and float(flat["fps"]) > 0:
        return 1000.0 / float(flat["fps"])
    return None


def stats(v):
    q = statistics.quantiles(v, n=4, method="inclusive") if len(v) >= 2 else [v[0]] * 3
    return statistics.median(v), q[2] - q[0]


def report(res):
    for t, v in res.items():
        if v:
            m, iqr = stats(v)
            print(f"GFXR_STAT tag={t} runs={len(v)} median_ms_frame={m:.3f} iqr_ms={iqr:.3f} min={min(v):.3f} max={max(v):.3f}")
        else:
            print(f"GFXR_STAT tag={t} no measurements")
    tags = list(res)
    if len(tags) == 2 and all(res[t] for t in tags):
        ma, mb = statistics.median(res[tags[0]]), statistics.median(res[tags[1]])
        print(f"GFXR_AB {tags[1]} vs {tags[0]}: {100.0 * (mb - ma) / ma:+.2f}% median ms/frame (box RTX 3060, a guide, not proof)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=str(ROOT), help="worktree whose HEAD box_run builds")
    sp = ap.add_subparsers(dest="cmd", required=True)
    c = sp.add_parser("capture")
    c.add_argument("--tag", required=True)
    c.add_argument("--mission", default="mc2_10")
    c.add_argument("--bookmarks", default="mc2_10_camera", help="bookmark file stem under tests/visual/bookmarks (one pose per file is best)")
    c.add_argument("--pose", default="wolfman", help="bookmark name inside the file")
    c.add_argument("--frames", type=int, default=10, help="N frames to capture")
    c.add_argument("--start", type=int, default=215, help="first captured frame (1-based present count)")
    c.add_argument("--trigger-frame", type=int, default=200)
    r = sp.add_parser("replay")
    r.add_argument("--tag", required=True)
    b = sp.add_parser("ab")
    b.add_argument("--a", required=True)
    b.add_argument("--b", required=True)
    for p in (r, b):
        p.add_argument("-n", type=int, default=7)
        p.add_argument("--gpu", default="auto")
        p.add_argument("--extra", default="", help="extra gfxrecon-replay args")
    a = ap.parse_args()
    if a.cmd == "capture":
        return cmd_capture(a)
    if a.cmd == "replay":
        rc, res = cmd_replay(a)
    else:
        rc, res = cmd_replay(a, [a.a, a.b])
    report(res)
    return rc


if __name__ == "__main__":
    sys.exit(main())
