#!/usr/bin/env python3
"""gate_registry_gen -- the derived artifacts of the gate table (typed gate registry, slice G2).

The compiled table (Gates/gate_table.json, emitted by tools/gate_dump) is the one source. From it this
module writes and checks:

  RenderCore/RendererFeatureRegistry.h   the two row tables kFeatureTable and kAuxEnvVars. The
                                         RendererFeature enum, DeviceCaps and the dump function stay
                                         hand-written; kFeatureTable is positional, so the order of its
                                         rows is the `order` of each row's registry(...) option.
  docs/flags.auto.yaml (v3)              one entry per gate, a pure function of the table.

Rows that have a registry entry but no environment variable (reverse-Z is always on) cannot be table rows;
they live in Gates/feature_only_rows.json.

USAGE: through tools/gate_gen.py --write / --check (this file has no CLI of its own).
"""
import json
import os
import re

HEADER_REL = "RenderCore/RendererFeatureRegistry.h"
YAML_REL = "docs/flags.auto.yaml"
ONLY_REL = "Gates/feature_only_rows.json"

GENERATED_NOTE = ("    // GENERATED by tools/gate_gen.py --write from Gates/gate_table.cpp (rows with a registry(...) option);\n"
                  "    // edit the table, not this list.\n")


def _cpp(s):
    return '"' + s.replace(chr(92), chr(92) * 2).replace('"', chr(92) + '"') + '"'


def _read(root, rel):
    with open(os.path.join(root, rel.replace("/", os.sep)), "r", encoding="utf-8", newline="") as fh:
        return fh.read()


def load_only_rows(root):
    p = os.path.join(root, ONLY_REL.replace("/", os.sep))
    if not os.path.isfile(p):
        return []
    with open(p, "r", encoding="utf-8") as fh:
        return json.load(fh)


def entries(doc, only):
    """[(table, order, featureId, envVar|None, kind, defaultOn, doc)] from the table JSON and the env-less rows."""
    out = []
    for g in doc["gates"]:
        r = g.get("registry")
        if not r:
            continue
        out.append(("feature" if r["order"] >= 0 else "aux", r["order"], r["featureId"], g["name"], r["kind"],
                    r["defaultOn"], g["doc"]))
    for o in only:
        out.append(("feature" if o["order"] >= 0 else "aux", o["order"], o["featureId"], None, o["kind"],
                    o["defaultOn"], o["doc"]))
    return out


_ENUM_RE = re.compile(r"^\s*(\w+)\s*=\s*(\d+),?\s*(?://\s*(.*))?$")


def parse_enum(text):
    """{index: (EnumName, trailing comment)} of `enum class RendererFeature` (COUNT excluded)."""
    t = text.replace("\r\n", "\n")
    m = re.search(r"enum class RendererFeature : int \{\n", t)
    if not m:
        raise SystemExit("gate_registry_gen: enum class RendererFeature not found in %s" % HEADER_REL)
    end = t.index("\n};", m.end())
    out = {}
    for line in t[m.end():end].split("\n"):
        mm = _ENUM_RE.match(line)
        if mm and mm.group(1) != "COUNT":
            out[int(mm.group(2))] = (mm.group(1), (mm.group(3) or "").strip())
    return out


def check_enum(enum, rows):
    """The enum and kFeatureTable must name the same positions; an env var named in the enum's trailing
    comment must be the row's."""
    if sorted(enum) != list(range(len(rows))):
        raise SystemExit("gate_registry_gen: RendererFeature has %d entries (indices %s) but kFeatureTable has %d rows"
                         % (len(enum), sorted(enum)[:3], len(rows)))
    for r in rows:
        name, comment = enum[r[1]]
        m = re.match(r"(MC2_[A-Z0-9_]+)\b", comment)
        if m and m.group(1) != r[3]:
            raise SystemExit("gate_registry_gen: %s (index %d) says %s but the table row is %s"
                             % (name, r[1], m.group(1), r[3] or r[2]))


def feature_rows(ents):
    rows = sorted((e for e in ents if e[0] == "feature"), key=lambda e: e[1])
    for i, e in enumerate(rows):
        if e[1] != i:
            raise SystemExit("gate_registry_gen: kFeatureTable order is not 0..N-1 (row %d has order %d: %s)"
                             % (i, e[1], e[2]))
    return rows


def aux_rows(ents):
    return sorted((e for e in ents if e[0] == "aux"), key=lambda e: (e[3] or e[2], e[2]))


def render_rows(rows, trailing_comma, enum=None, comments=None):
    lines = [GENERATED_NOTE]
    for _t, _o, fid, env, kind, don, doc in rows:
        if enum is not None:
            lines.append("    // [%d] %s\n" % (_o, enum[_o][0]))
        for c in (comments or {}).get(fid, []):
            lines.append("    %s\n" % c)
        lines.append("    {\n")
        lines.append("        %s, %s, EnvVarKind::%s, %s,\n" % (
            _cpp(fid), _cpp(env) if env else "nullptr", kind, "true" if don else "false"))
        lines.append("        %s%s\n" % (_cpp(doc), "," if trailing_comma else ""))
        lines.append("    },\n")
    return "".join(lines)


def patch_header(text, ents, comments=None):
    """The header with both row tables replaced by the generated rows."""
    crlf = "\r\n" in text
    t = text.replace("\r\n", "\n")
    frows = feature_rows(ents)
    enum = parse_enum(t)
    check_enum(enum, frows)
    for name, rows, comma in (("kFeatureTable", frows, False), ("kAuxEnvVars", aux_rows(ents), True)):
        start_pat = re.compile(r"static constexpr EnvVarDesc %s\[\] = \{\n" % name)
        m = start_pat.search(t)
        if not m:
            raise SystemExit("gate_registry_gen: %s declaration not found in %s" % (name, HEADER_REL))
        end = t.index("\n};\n", m.end())
        t = t[:m.end()] + render_rows(rows, comma, enum if name == "kFeatureTable" else None, comments) + t[end + 1:]
    return t.replace("\n", "\r\n") if crlf else t


def _num(x):
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, float) and x == int(x) and abs(x) < 1e15:
        return repr(float(x))
    return json.dumps(x)


def render_yaml(doc, only):
    gates = doc["gates"]
    n_reg = sum(1 for g in gates if g.get("registry")) + len(only)
    L = []
    L.append("# docs/flags.auto.yaml -- GENERATED by tools/gate_gen.py --write from Gates/gate_table.json. Do not edit.\n")
    L.append("# One entry per MC2_* gate in the compiled table (Gates/gate_table.cpp): a pure function of the table.\n")
    L.append("# Where each gate is read, what the smoke runner forwards and what tier1_env_vars.md says are not here: ask\n")
    L.append("# tools/repo_intel (env_var, gate_status), which scan the sources.\n")
    L.append("generator_version: \"3.0.0\"\n")
    L.append("gate_count: %d\n" % len(gates))
    L.append("registry_entry_count: %d\n" % n_reg)
    L.append("verified_count: %d\n" % sum(1 for g in gates if g.get("verified")))
    L.append("flags:\n")
    for g in gates:
        L.append("  - name: %s\n" % g["name"])
        L.append("    kind: %s\n" % g["kind"])
        L.append("    default: %s\n" % _num(g["default"]))
        L.append("    rule: %s\n" % g["rule"])
        L.append("    owner: %s\n" % g["owner"])
        if g.get("retireBy"):
            L.append("    retire_by: %s\n" % g["retireBy"])
        L.append("    doc: %s\n" % json.dumps(g["doc"], ensure_ascii=True))
        if g.get("tokens"):
            L.append("    tokens: %s\n" % json.dumps(g["tokens"]))
        if g.get("inherits"):
            L.append("    inherits: %s\n" % g["inherits"])
        rg = g.get("range")
        if rg:
            L.append("    range: {lo: %s, hi: %s, style: %s%s}\n" % (
                _num(rg["lo"]), _num(rg["hi"]), "clamp" if rg.get("clamp") else "reject",
                ", lo_exclusive: true" if rg.get("loExclusive") else ""))
        for key, name in (("reread", "reread"), ("divergent", "divergent"), ("smokePassthrough", "smoke_passthrough"),
                          ("verified", "verified")):
            if g.get(key):
                L.append("    %s: true\n" % name)
        reg = g.get("registry")
        if reg:
            L.append("    registry: {feature_id: %s, kind: %s, order: %d, default_on: %s}\n" % (
                reg["featureId"], reg["kind"], reg["order"], "true" if reg["defaultOn"] else "false"))
    if only:
        L.append("feature_only_rows:   # registry entries with no environment variable\n")
        for o in only:
            L.append("  - {feature_id: %s, kind: %s, order: %d, default_on: %s}\n" % (
                o["featureId"], o["kind"], o["order"], "true" if o["defaultOn"] else "false"))
    return "".join(L)


def generate(root, doc):
    """(header_text, yaml_text) for the current table document."""
    only = load_only_rows(root)
    ents = entries(doc, only)
    comments = {o["featureId"]: o["comment"] for o in only if o.get("comment")}
    return patch_header(_read(root, HEADER_REL), ents, comments), render_yaml(doc, only)


def write_all(root, doc):
    header, yaml = generate(root, doc)
    for rel, text in ((HEADER_REL, header), (YAML_REL, yaml)):
        with open(os.path.join(root, rel.replace("/", os.sep)), "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    return [HEADER_REL, YAML_REL]


def check_all(root, doc):
    """Failure strings for a stale header or yaml."""
    fails = []
    try:
        header, yaml = generate(root, doc)
        have_header = _read(root, HEADER_REL)
        have_yaml = _read(root, YAML_REL)
    except SystemExit as ex:
        return [str(ex)]
    except OSError as ex:
        return ["cannot read a derived registry file: %s (run py -3 tools/gate_gen.py --write)" % ex]
    if have_header.replace("\r\n", "\n") != header.replace("\r\n", "\n"):
        fails.append("%s rows are stale against the gate table: run py -3 tools/gate_gen.py --write" % HEADER_REL)
    if have_yaml.replace("\r\n", "\n") != yaml:
        fails.append("%s is stale against the gate table: run py -3 tools/gate_gen.py --write" % YAML_REL)
    return fails
