def add_allow_nonstock_arg(ap) -> None:
    """Add `--allow-nonstock` once per parser (idempotent)."""
    if any("--allow-nonstock" in (getattr(a, "option_strings", []) or [])
           for a in getattr(ap, "_actions", [])):
        return
    ap.add_argument("--allow-nonstock", action="store_true",
                    help="proceed on source data that does NOT match the "
                         "shipped bytes (modded/custom assets). Prints a loud "
                         "banner; results do not describe stock data.")


def allow_nonstock_from_args(args) -> bool:
    return bool(getattr(args, "allow_nonstock", False))


def _main(argv: Sequence[str]) -> int:
    import argparse
    ap = argparse.ArgumentParser(
        description="Resolve + verify a stock data corpus (tgl/textures/objects).")
    ap.add_argument("corpus", choices=sorted(CORPORA))
    ap.add_argument("names", nargs="*",
                    help="corpus-relative member names (default: whole corpus)")
    ap.add_argument("--dir", default=None, help="explicit source dir to verify")
    add_allow_nonstock_arg(ap)
    args = ap.parse_args(argv)
    try:
        res = resolve(args.corpus, explicit=args.dir, names=args.names or None,
                      allow_nonstock=args.allow_nonstock, quiet=True)
    except StockDataError as e:
        print(f"[stock-corpus] ERROR {e}", file=sys.stderr)
        return 2
    print(res.dir)
    print(res.banner(), file=sys.stderr)
    if res.caveat:
        print(f"  caveat: {res.caveat}", file=sys.stderr)
    return 0 if res.verified else 2


