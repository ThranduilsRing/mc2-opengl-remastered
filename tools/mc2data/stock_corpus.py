@dataclass
class ResolvedCorpus(Resolved):
    """`Resolved` plus the facts a corpus proof has and a mission proof does not."""

    corpus: str = ""
    engine_only: int = 0     # shipped members with no source counterpart (skipped)
    unshipped: int = 0       # source files with no shipped counterpart (unprovable)
    caveat: str = ""

    def banner(self) -> str:
        if self.verified:
            extra = ""
            if self.engine_only:
                extra += (f"; {self.engine_only} engine-only member(s) have no "
                          f"source counterpart and were not checked")
            if self.unshipped:
                extra += (f"; {self.unshipped} source file(s) are NOT shipped and "
                          f"cannot be proven by any manifest")
            return (f"[stock-{self.corpus}] {self.dir}  ({self.label}; "
                    f"{self.checked} file(s) match the shipped {self.note or 'archive'}"
                    f"{extra})")
        return (f"[stock-{self.corpus}] !! UNVERIFIED !! {self.dir}  ({self.label}; "
                f"{len(self.mismatches)} file(s) differ from the shipped archive) "
                f"-- results do NOT describe stock data")

    def member(self, name: str) -> Path:
        """On-disk path of a corpus member, resolved case-insensitively.

        FST member names are lowercased (`64overlays/runway0011.tga`); the
        directory on disk is not (`64Overlays`). Joining the lowercase name
        happens to work on Windows and silently breaks elsewhere, so callers
        go through here instead.
        """
        key = str(name).strip().replace("\\", "/").lstrip("/").lower()
        p = source_index(self.dir).get(key)
        if p is None:
            raise StockDataError(
                f"{self.dir}: corpus {self.corpus!r} has no member {name!r}")
        return p


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------

def load_corpus_manifest(c: Corpus,
                         path: Path = MANIFEST_PATH) -> dict[str, str]:
    """{relpath under the corpus prefix -> md5hex}, from `stock_data.md5`."""
    if not path.is_file():
        raise StockDataError(
            f"stock data manifest missing: {path}\n"
            f"  regenerate with: py -3 scripts/check-stock-mission-data.py "
            f"--write-corpora")
    full = load_manifest(path)          # shared parser; keys already lowercased
    pre = c.prefix.lower()
    out = {k[len(pre):]: v for k, v in full.items() if k.startswith(pre)}
    if not out:
        raise StockDataError(
            f"{path} carries no members under {c.prefix!r} -- the manifest was "
            f"generated before corpus {c.name!r} existed; re-run "
            f"scripts/check-stock-mission-data.py --write-corpora")
    return out


def corpus_manifest_header(path: Path = MANIFEST_PATH) -> dict[str, str]:
    return manifest_header(path)


# ---------------------------------------------------------------------------
# Case-insensitive source index
#
# FST member names are stored lowercased; real directories are not
# (`64Overlays` on disk vs `64overlays/` in textures.fst). Relying on the
# Windows filesystem to paper over that would make this module silently
# wrong on a case-sensitive filesystem -- i.e. exactly the kind of
# platform-dependent truth this arc is about.
# ---------------------------------------------------------------------------

_INDEX_CACHE: dict[str, dict[str, Path]] = {}


def source_index(directory: Path) -> dict[str, Path]:
    key = str(Path(directory).resolve()).lower()
    hit = _INDEX_CACHE.get(key)
    if hit is not None:
        return hit
    root = Path(directory)
    out: dict[str, Path] = {}
    for p in root.rglob("*"):
        if p.is_file():
            out[str(p.relative_to(root)).replace("\\", "/").lower()] = p
    _INDEX_CACHE[key] = out
    return out


# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------

def verify_dir(c: Corpus, directory: Path,
               names: Optional[Iterable[str]] = None,
               manifest: Optional[dict[str, str]] = None
               ) -> tuple[bool, int, list[str], int, int]:
    """Return (ok, n_checked, mismatches, engine_only_skipped, unshipped).

    `names` are corpus-relative member names (`compbas.csv`,
    `128/a_quonset.tga`). None -> the whole corpus.

    A REQUESTED name absent from the manifest is a MISMATCH: the caller is
    reading something the engine does not ship, and saying so beats grading it
    as if it were stock.

    A member absent from the source dir is a mismatch UNLESS its extension is
    declared engine-only for this corpus -- `.tgl`/`.agl` are compiled from
    `.ase` and never appear in a source checkout. Note the asymmetry on
    purpose: an engine-only file that IS present gets verified like anything
    else. The skip is "no source counterpart exists", not "this extension is
    exempt".
    """
    man = manifest if manifest is not None else load_corpus_manifest(c)
    directory = Path(directory)
    idx = source_index(directory)
    bad: list[str] = []

    if names is None:
        keys = sorted(man)
    else:
        keys = []
        for raw in names:
            k = str(raw).strip().replace("\\", "/").lstrip("/").lower()
            if not k:
                continue
            if k not in man:
                bad.append(f"{k}: not stock (absent from the shipped {c.fst})")
            else:
                keys.append(k)
        keys = sorted(set(keys))

    if not keys and not bad:
        return False, 0, ["nothing to verify (no manifest keys selected)"], 0, 0

    n = 0
    engine_only = 0
    for k in keys:
        p = idx.get(k)
        if p is None:
            ext = k.rsplit(".", 1)[-1] if "." in k else ""
            if ext in c.engine_only_exts:
                engine_only += 1
                continue
            bad.append(f"{k}: ABSENT")
            continue
        got = _md5(p)
        n += 1
        if got != man[k]:
            bad.append(f"{k}: DIFFERS (have {got[:12]}, shipped {man[k][:12]})")

    unshipped = 0
    if names is None:
        unshipped = sum(1 for k in idx if k not in man)

    return (not bad), n, bad, engine_only, unshipped


# ---------------------------------------------------------------------------
# Resolution
# ---------------------------------------------------------------------------

def resolve(corpus_name: str,
            explicit: Optional[str | Path] = None,
            names: Optional[Iterable[str]] = None,
            *,
            allow_nonstock: bool = False,
            quiet: bool = False,
            candidates: Optional[Sequence[str]] = None,
            fst_roots: Optional[Sequence[str]] = None,
            allow_fst_extract: bool = True,
            manifest_path: Path = MANIFEST_PATH) -> ResolvedCorpus:
    """Locate a source copy of `corpus_name` and PROVE it is what ships.

    Resolution order -- AUTHORITY FIRST, which is the specific bug in
    `mc2weapon.py`: it searched the editable srcdata clone BEFORE anything
    deployed, so a local edit would silently win. Note that reordering alone
    would have fixed nothing there: no deploy lane carries a loose
    `data/objects/compbas.csv`, so the "deploy" rung it was ordered behind
    never resolved on this machine and never will. Verification is the fix;
    ordering is hygiene on top of it.

        explicit dir  ->  $MC2_STOCK_<X>_DIR  ->  automatic candidates
                      ->  extract straight out of the deployed <corpus>.fst

    Never returns unverified data unless `allow_nonstock`, in which case it
    returns it and shouts on stderr. Raises `StockDataError` otherwise.
    """
    c = corpus(corpus_name)
    man = load_corpus_manifest(c, manifest_path)
    cands = tuple(c.candidates) if candidates is None else tuple(candidates)
    roots = CANDIDATE_FST_ROOTS if fst_roots is None else tuple(fst_roots)
    if os.environ.get(ENV_ALLOW_NONSTOCK) == "1":
        allow_nonstock = True

    def _mk(d: Path, label: str, ok: bool, n: int, bad: list[str],
            eo: int, un: int) -> ResolvedCorpus:
        return ResolvedCorpus(dir=d, label=label, verified=ok, checked=n,
                              stems=tuple(str(x) for x in (names or ())),
                              note=c.fst, mismatches=tuple(bad),
                              corpus=c.name, engine_only=eo, unshipped=un,
                              caveat=c.note)

    # --- explicit dir -----------------------------------------------------
    if explicit:
        d = Path(explicit)
        if not d.is_dir():
            raise StockDataError(f"{c.name} source dir does not exist: {d}")
        ok, n, bad, eo, un = verify_dir(c, d, names, man)
        res = _mk(d, "explicit dir", ok, n, bad, eo, un)
        if ok:
            if not quiet:
                print(res.banner(), file=sys.stderr)
            return res
        if allow_nonstock:
            _shout(res)
            return res
        raise StockDataError(_failure_text(c, d, bad))

    # --- env override, then automatic candidates --------------------------
    ordered: list[tuple[str, str]] = []
    env = os.environ.get(c.env, "").strip()
    if env:
        ordered.append((f"${c.env}", env))
    ordered += [("candidate", x) for x in cands]

    tried: list[str] = []
    first_unverified: Optional[ResolvedCorpus] = None
    for label, cand in ordered:
        d = Path(cand)
        if not d.is_dir():
            tried.append(f"  {cand}  -- not present on this machine")
            continue
        ok, n, bad, eo, un = verify_dir(c, d, names, man)
        if ok:
            res = _mk(d, label, True, n, bad, eo, un)
            if not quiet:
                print(res.banner(), file=sys.stderr)
            return res
        if first_unverified is None:
            first_unverified = _mk(d, label, False, n, bad, eo, un)
        tried.append(f"  {cand}  -- {len(bad)} mismatch(es), e.g. {bad[0]}")

    # --- explicit opt-out: the caller's OWN tree wins ---------------------
    # `allow_nonstock` means "I am deliberately working on non-stock assets".
    # Handing such a caller the stock extract instead of the tree they pointed
    # at would be actively wrong, so the first existing candidate wins here --
    # loudly. Without this the flag only affected the explicit-dir path, and a
    # modded/synthetic tree silently fell through to stock data.
    if allow_nonstock and first_unverified is not None:
        _shout(first_unverified)
        return first_unverified

    # --- last resort: materialize out of the deployed archive -------------
    if allow_fst_extract:
        fst = find_deployed_fst(roots, c.fst)
        if fst is not None:
            d = materialize_from_fst(fst, prefix=c.prefix)
            ok, n, bad, eo, un = verify_dir(c, d, names, man)
            if ok:
                res = _mk(d, f"extracted from {fst}", True, n, bad, eo, un)
                if not quiet:
                    print(res.banner(), file=sys.stderr)
                return res
            tried.append(f"  {fst}  -- extracted, but {len(bad)} mismatch(es): "
                         f"the deployed archive DISAGREES with the committed "
                         f"manifest, e.g. {bad[0]}")
        else:
            tried.append(f"  (no deployed {c.fst} found in any known lane)")

    raise StockDataError(
        f"could not locate VERIFIED stock {c.name} data.\n"
        "Tried, in order:\n" + "\n".join(tried) + "\n"
        f"Fix one of these:\n"
        f"  * pass an explicit directory holding the stock {c.name} files\n"
        f"  * set {c.env}=<dir>\n"
        f"  * pass --allow-nonstock if you MEANT to use non-stock data\n"
        f"Refusing to guess: wrong source data produces plausible numbers "
        f"about assets the engine never loads, silently.")


_CACHE: dict[tuple, Optional[ResolvedCorpus]] = {}


def resolve_or_none(corpus_name: str,
                    names: Optional[Iterable[str]] = None,
                    **kw) -> Optional[ResolvedCorpus]:
    """Non-raising variant for module-level use (pytest `skipif`, etc).

    Returns a VERIFIED resolution or None. It never returns unverified data --
    a test that cannot get stock data must SKIP, not pass against the wrong
    bytes. Memoised per process; resolution md5s files.
    """
    key = (corpus_name, tuple(sorted(str(n) for n in names)) if names else None,
           tuple(sorted(kw.items())) if kw else None)
    if key in _CACHE:
        return _CACHE[key]
    try:
        r = resolve(corpus_name, names=names, quiet=True, **kw)
        if not r.verified:
            r = None
    except StockDataError:
        r = None
    _CACHE[key] = r
    return r


def _failure_text(c: Corpus, d: Path, bad: list[str]) -> str:
    head = "\n".join(f"    {b}" for b in bad[:12])
    more = f"\n    ... and {len(bad) - 12} more" if len(bad) > 12 else ""
    return (f"{d} is NOT the stock {c.name} data the engine ships.\n"
            f"  {len(bad)} file(s) disagree with the shipped {c.fst}:\n"
            f"{head}{more}\n"
            f"  Analysis of this data does NOT describe stock assets.\n"
            f"  Pass --allow-nonstock if that is deliberate (modded/custom "
            f"asset), or drop the explicit dir to let the resolver find "
            f"verified data.")


def _shout(res: ResolvedCorpus) -> None:
    bar = "!" * 78
    print(f"\n{bar}\n{res.banner()}", file=sys.stderr)
    for b in res.mismatches[:8]:
        print(f"    {b}", file=sys.stderr)
    if len(res.mismatches) > 8:
        print(f"    ... and {len(res.mismatches) - 8} more", file=sys.stderr)
    print("  proceeding because --allow-nonstock was given.\n"
          f"{bar}\n", file=sys.stderr)


# ---------------------------------------------------------------------------
# argparse glue
