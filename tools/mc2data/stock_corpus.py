# AUTOMATIC candidate only if it is a pristine extract. A WORKING CHECKOUT MUST
# NOT BE LISTED HERE, however convenient. `A:/Games/mc2-srcdata/*` is a working
# checkout; it stays reachable through an explicit dir, $MC2_STOCK_<X>_DIR, or
# a caller-supplied probe list (`tools/blender_pipeline/srcdata.py` passes its
# historical probe order) -- in every one of those routes it is byte-verified
# per name before use.
#
# Carver5-feasibility is ABSENT ON PURPOSE. Do not add it.
# ---------------------------------------------------------------------------
