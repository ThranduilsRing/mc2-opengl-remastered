@dataclass(frozen=True)
class Corpus:
    """One FST-backed data corpus, and how to find/prove a source copy."""

    name: str
    fst: str                       # archive filename inside a deploy lane
    prefix: str                    # FST member prefix, e.g. "data/tgl/"
    env: str                       # $MC2_STOCK_<X>_DIR override
    candidates: tuple[str, ...]    # AUTOMATIC candidates: pristine extracts only
    engine_only_exts: tuple[str, ...] = ()   # shipped, but never a source file
    note: str = ""
    # Why `candidates` is deliberately empty, when it is. An empty list with no
    # reason is a bug (someone deleted the last entry); an empty list WITH a
    # measured reason is the correct state for a corpus no source tree
    # reproduces. `scripts/check-stock-mission-data.py` enforces the
    # distinction so "empty" can never mean "unexamined".
    no_candidate_reason: str = ""


# ---------------------------------------------------------------------------
