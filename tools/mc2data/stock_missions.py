#!/usr/bin/env python3
"""STOCK-DATA-TRUTH-1 -- one verified answer to "where is the stock mission data?".

WHY THIS EXISTS
---------------
Eight offline tools defaulted `--missions-dir` (or a module constant) to
`A:/Games/Carver5-feasibility/data/missions` and called it "stock mission data".
It is not. Measured against the shipped `mission.fst`, that tree differs on
**all 24 campaign maps** -- every `mc2_01..mc2_24` `.pak` AND `.fit`. A lane
running the analyzer with default flags therefore graded terrain the engine
never loads, and came within one meta-review of publishing a confident
go/no-go on it (`.claude/SHORELINE-V0-FALSIFY-1-STATUS.md` section 0a).

WHAT IS AUTHORITATIVE, AND WHY
------------------------------
The engine's resolution ladder is `mclib/file.cpp` `fileExists()` /
`File::open()`:

    active mod overlay  ->  loose file on disk  ->  FastFile (.fst)

For every `mc2_*` map, in every deploy lane, the first two rungs miss and the
bytes come from `mission.fst`. (Verified: no loose file in any lane shadows an
FST member -- the loose files are all test fixtures and the custom
`gaea_peaks_01` map, none of which are FST members.) So the **deployed
`mission.fst` is the authority, definitionally**.

A source tree is never authoritative on its own. It is usable only by PROVING
it equals the authority. That proof is `stock_missions.md5`, a committed digest
of every `data/missions/*` member of the shipped FST, generated by
`scripts/check-stock-mission-data.py --write`.

Consequences of that framing, all of which this module implements:

  * A directory is accepted only after its bytes match the manifest. An
    unverifiable directory is REFUSED, never silently used.
  * Requiring `--missions-dir` would NOT have prevented the original defect --
    the wrong path arrived in a brief; a required flag would have had the lane
    type the same wrong path and get the same silence. Verification is the
    fix; requiredness is not. The flag therefore stays optional.
  * With no deploy and no verified source tree present, the module materializes
    the missions straight out of a deployed `mission.fst` into a temp cache, so
    the authority is always reachable when an install exists.

MEASURED STATE (2026-07-30, this machine)
-----------------------------------------
  * `mission.fst` md5 `1e7935dc33fe...` is BYTE-IDENTICAL across every deploy
    lane that has one -- 0.4, 0.4c, 0.4d-rc1, 0.5.1 -- all 1346 members agree.
    "Which lane?" is currently a non-question; the manifest makes it stay one,
    because a lane that ever diverges fails verification instead of being
    silently preferred.
  * `A:/Games/mc2-opengl/mc2srcdata-fresh/missions/` reproduces ALL 1344
    `data/missions/` members byte-for-byte -- 0 differ, 0 absent, checked
    recursively over the whole archive, not a sampled subset.
  * `A:/Games/mc2-srcdata/missions/` differs on mc2_01 AND mc2_13 (a working
    checkout with local edits -- the ones `docs/data-provenance.md` flags as
    "have NOT shipped"). It is deliberately NOT an automatic candidate; reach
    it with `--missions-dir` and it is verified per-stem.
  * `A:/Games/Carver5-feasibility/data/missions/` differs from the shipped
    bytes on ALL 24 campaign maps, `.pak` and `.fit`. Deliberately NOT a
    candidate.

WHAT ACTUALLY DIFFERS IN THE CARVER5 TREE (measured, all 24 maps)
----------------------------------------------------------------
Do not read "different md5" as "different terrain" -- it was worth decoding.
Comparing the decoded `PostcompVertex` grids field by field:

  * `elevation`  -- **BIT-IDENTICAL on all 24 maps** (max |delta| = 0.0).
    Carver5's paks are the same heightfield stored uncompressed (packet type
    RAW vs the shipped ZLIB), which is most of the 2.9 MB vs 394 KB size gap.
  * `[Water] Elevation` in the `.fit` -- identical on all 24.
  * `textureData` (base TXM + hi16 overlay handle) -- differs, 137..14121
    vertices per map.
  * `terrainType` -- differs on 11 maps, up to 14076 vertices.
  * packed `water` alpha byte -- differs on all 24, ~7.4k-10.7k vertices.
  * vertex `normal` -- differs on all 24, 2.5k-9.8k vertices.
  * terrain object records -- differ on mc2_04/05/06/11 (up to 14 objects).
  * every `.fit` differs (camera params, `ObjectNumber` lists, `NewScale`).

So a HEIGHT-only analysis would have reached the same answer either way --
worth stating plainly rather than overclaiming. But anything reading overlays,
terrain type, normals, or the object list (cook_markings, overlay_extract,
control-map classification, scatter exclusion, smooth-pass footprint
protection) WAS reading different data. And nothing in the tooling knew which
it was doing. That is the actual defect: not "the numbers were wrong" but
"nobody could tell whether they were."

USAGE
-----
    from stock_missions import add_missions_dir_arg, resolve_from_args

    add_missions_dir_arg(ap)                     # --missions-dir / --allow-nonstock
    ...
    res = resolve_from_args(args, missions=args.missions)
    missions_dir = res.dir

Escape hatches, both loud:
  * `--allow-nonstock` -- proceed on unverified data, printing a stderr banner
    on every run. For modded/custom/authored maps, which are legitimately not
    stock.
  * `MC2_STOCK_MISSIONS_DIR` -- point the resolver at an install elsewhere. It
    is still verified; the env var chooses a candidate, it does not bless one.
"""
