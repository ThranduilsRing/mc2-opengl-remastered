# Manifest
# ---------------------------------------------------------------------------

def load_manifest(path: Path = MANIFEST_PATH) -> dict[str, str]:
    """Return {relpath-under-data/missions -> md5hex} from the committed digest."""
    if not path.is_file():
        raise StockDataError(
            f"stock mission manifest missing: {path}\n"
            f"  regenerate with: py -3 scripts/check-stock-mission-data.py --write")
    out: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        digest, _, name = line.partition("  ")
        if not name:
            raise StockDataError(f"malformed manifest line in {path}: {line!r}")
        out[name.strip().replace("\\", "/").lower()] = digest.strip().lower()
    if not out:
        raise StockDataError(f"stock mission manifest is empty: {path}")
    return out


def manifest_header(path: Path = MANIFEST_PATH) -> dict[str, str]:
    """Parse the `# key: value` header lines out of the manifest."""
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("#"):
            break
        m = re.match(r"^#\s*([a-z0-9_]+):\s*(.+?)\s*$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def _md5(p: Path) -> str:
    h = hashlib.md5()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


# ---------------------------------------------------------------------------
# FST reading (format per mclib/ffile.cpp: u32 version, u32 numFiles, then
# 266-byte entries {offset,size,realSize,hash,char name[250]}; payload is zlib
# when size != realSize).
# ---------------------------------------------------------------------------

def fst_members(fst: Path) -> tuple[bytes, list[tuple[str, int, int, int]]]:
    data = fst.read_bytes()
    if len(data) < 8:
        raise StockDataError(f"not a FastFile (too short): {fst}")
    _ver, n = struct.unpack_from("<II", data, 0)
    if n <= 0 or 8 + n * 266 > len(data):
        raise StockDataError(f"not a FastFile (bad numFiles={n}): {fst}")
    out = []
    for i in range(n):
        off, size, real, _h, name = _FST_ENTRY.unpack_from(data, 8 + i * 266)
        nm = name.split(b"\0", 1)[0].decode("latin-1").replace("\\", "/").lower()
        out.append((nm, off, size, real))
    return data, out


def fst_blob(data: bytes, off: int, size: int, real: int) -> Optional[bytes]:
    raw = data[off:off + size]
    if size == real:
        return raw
    try:
        return zlib.decompress(raw)
    except zlib.error:
        return None


def fst_digests(fst: Path, prefix: str) -> dict[str, str]:
    """{relpath under `prefix` -> md5hex} for every member under `prefix`.

    `prefix` is parameterised so the SAME reader serves every FST-backed
    corpus (`data/missions/` here, `data/tgl/` and `data/textures/` and
    `data/objects/` in `stock_corpus.py`). One FST parser in this repo, not
    one per corpus -- a second copy is how two "authorities" start disagreeing.
    """
    data, ms = fst_members(fst)
    out: dict[str, str] = {}
    for nm, off, size, real in ms:
        if not nm.startswith(prefix):
            continue
        blob = fst_blob(data, off, size, real)
        if blob is None:
            raise StockDataError(f"{fst}: member {nm} failed zlib decompress")
        out[nm[len(prefix):]] = hashlib.md5(blob).hexdigest()
    return out


def fst_mission_digests(fst: Path) -> dict[str, str]:
    """{relpath under data/missions -> md5hex} for every mission member."""
    return fst_digests(fst, MANIFEST_PREFIX)


def find_deployed_fst(roots: Sequence[str] = CANDIDATE_FST_ROOTS,
                      name: str = "mission.fst") -> Optional[Path]:
    for r in roots:
        p = Path(r) / name
        if p.is_file():
            return p
    return None


def materialize_from_fst(fst: Path, cache_root: Optional[Path] = None,
                         prefix: str = MANIFEST_PREFIX) -> Path:
    """Extract `<prefix>*` out of a deployed FST into a temp cache dir.

    Keyed by the FST's own md5 AND the prefix, so two different archives (or
    two different corpora out of one archive) never share a cache and a re-run
    over the same pair is a no-op.
    """
    digest = _md5(fst)
    root = cache_root or Path(tempfile.gettempdir()) / "mc2_stock_missions"
    tag = prefix.strip("/").replace("/", "_")
    out = root / (digest[:12] if prefix == MANIFEST_PREFIX else f"{digest[:12]}-{tag}")
    stamp = out / ".complete"
    if stamp.is_file():
        return out
    data, ms = fst_members(fst)
    out.mkdir(parents=True, exist_ok=True)
    n = 0
    for nm, off, size, real in ms:
        if not nm.startswith(prefix):
            continue
        rel = nm[len(prefix):]
        blob = fst_blob(data, off, size, real)
        if blob is None:
            continue
        dst = out / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(blob)
        n += 1
    stamp.write_text(f"{fst}\n{digest}\n{n}\n", encoding="utf-8", newline="\n")
    return out


