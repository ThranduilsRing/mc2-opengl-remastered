def add_missions_dir_arg(ap, *, required: bool = False) -> None:
    """Add the `--missions-dir` / `--allow-nonstock` pair.

    NOTE the absent `default=`. A hard-coded absolute default is the defect
    (STOCK-DATA-TRUTH-1); `scripts/check-stock-mission-data.py` fails the build
    if one reappears.
    """
    ap.add_argument("--missions-dir", required=required, default=None,
                    help="stock mission .pak/.fit dir. Omit to auto-resolve "
                         "against the shipped mission.fst digest "
                         "(tools/mc2data/stock_missions.md5). Whatever is used "
                         "is byte-verified; unverifiable data is refused.")
    ap.add_argument("--allow-nonstock", action="store_true",
                    help="proceed on mission data that does NOT match the "
                         "shipped bytes (modded/custom maps). Prints a loud "
                         "banner; results do not describe stock terrain.")


def resolve_from_args(args, missions: Optional[Iterable[str]] = None,
                      *, quiet: bool = False) -> Resolved:
    return resolve_missions_dir(
        explicit=getattr(args, "missions_dir", None),
        missions=missions,
        allow_nonstock=bool(getattr(args, "allow_nonstock", False)),
        quiet=quiet)


def _main(argv: Sequence[str]) -> int:
    import argparse
    ap = argparse.ArgumentParser(
        description="Resolve + verify the stock mission-data directory.")
    add_missions_dir_arg(ap)
    ap.add_argument("missions", nargs="*", help="mission stems to verify "
                                                "(default: the whole corpus)")
    args = ap.parse_args(argv)
    try:
        res = resolve_from_args(args, missions=args.missions or None, quiet=True)
    except StockDataError as e:
        print(f"[stock-missions] ERROR {e}", file=sys.stderr)
        return 2
    print(res.dir)
    print(res.banner(), file=sys.stderr)
    return 0 if res.verified else 2


if __name__ == "__main__":
    raise SystemExit(_main(sys.argv[1:]))
