def resolve_missions_dir(explicit: Optional[str | Path] = None,
                         missions: Optional[Iterable[str]] = None,
                         *,
                         allow_nonstock: bool = False,
                         quiet: bool = False,
                         manifest_path: Path = MANIFEST_PATH,
                         candidates: Optional[Sequence[str]] = None,
                         fst_roots: Optional[Sequence[str]] = None,
                         allow_fst_extract: bool = True) -> Resolved:
    """Locate stock mission data and PROVE it is what the engine ships.

    Never returns an unverified directory unless `allow_nonstock` is set, in
    which case it returns one and shouts about it on stderr. Raises
    StockDataError otherwise.

    `candidates` / `fst_roots` default to the module globals READ AT CALL TIME,
    not bound at def time, so a test can monkeypatch CANDIDATE_DIRS.
    """
    candidates = CANDIDATE_DIRS if candidates is None else candidates
    fst_roots = CANDIDATE_FST_ROOTS if fst_roots is None else fst_roots
    man = load_manifest(manifest_path)
    if os.environ.get(ENV_ALLOW_NONSTOCK) == "1":
        allow_nonstock = True

    # --- explicit path (CLI flag) -----------------------------------------
    if explicit:
        d = Path(explicit)
        if not d.is_dir():
            raise StockDataError(f"--missions-dir does not exist: {d}")
        ok, n, bad = verify_dir(d, missions, man)
        res = Resolved(dir=d, label="explicit --missions-dir", verified=ok,
                       checked=n, stems=tuple(missions or ()),
                       mismatches=tuple(bad))
        if ok:
            if not quiet:
                print(res.banner(), file=sys.stderr)
            return res
        if allow_nonstock:
            _shout(res)
            return res
        raise StockDataError(_explicit_failure_text(d, bad))

    # --- env override ------------------------------------------------------
    env = os.environ.get(ENV_OVERRIDE, "").strip()
    ordered: list[tuple[str, str]] = []
    if env:
        ordered.append((f"${ENV_OVERRIDE}", env))
    ordered += [("candidate", c) for c in candidates]

    tried: list[str] = []
    for label, cand in ordered:
        d = Path(cand)
        if not d.is_dir():
            tried.append(f"  {cand}  -- not present on this machine")
            continue
        ok, n, bad = verify_dir(d, missions, man)
        if ok:
            res = Resolved(dir=d, label=label, verified=True, checked=n,
                           stems=tuple(missions or ()),
                           note="matches the shipped mission.fst")
            if not quiet:
                print(res.banner(), file=sys.stderr)
            return res
        tried.append(f"  {cand}  -- {len(bad)} mismatch(es), e.g. {bad[0]}")

    # --- last resort: materialize straight out of a deployed mission.fst ---
    if allow_fst_extract:
        fst = find_deployed_fst(fst_roots)
        if fst is not None:
            d = materialize_from_fst(fst)
            ok, n, bad = verify_dir(d, missions, man)
            if ok:
                res = Resolved(dir=d, label=f"extracted from {fst}", verified=True,
                               checked=n, stems=tuple(missions or ()),
                               note="materialized from the deployed FastFile")
                if not quiet:
                    print(res.banner(), file=sys.stderr)
                return res
            tried.append(f"  {fst}  -- extracted, but {len(bad)} mismatch(es): "
                         f"the deployed archive DISAGREES with the committed "
                         f"manifest, e.g. {bad[0]}")
        else:
            tried.append("  (no deployed mission.fst found in any known lane)")

    raise StockDataError(
        "could not locate VERIFIED stock mission data.\n"
        "Tried, in order:\n" + "\n".join(tried) + "\n"
        f"Fix one of these:\n"
        f"  * pass --missions-dir <dir> holding the stock .pak/.fit files\n"
        f"  * set {ENV_OVERRIDE}=<dir>\n"
        f"  * pass --allow-nonstock if you MEANT to analyze non-stock data\n"
        f"Refusing to guess: a wrong mission dir grades terrain the engine "
        f"never loads, and does it silently.")


_CACHE: dict[tuple, Optional[Resolved]] = {}


def stock_missions_dir_or_none(missions: Optional[Iterable[str]] = None
                               ) -> Optional[Path]:
    """Non-raising variant for module-level use (pytest `skipif`, etc).

    Returns the verified stock mission dir, or None when there is none on this
    machine. It NEVER returns an unverified directory -- a test that would
    otherwise assert against the wrong terrain must skip, not pass.
    Memoized per-process; resolution md5s files.
    """
    key = ("or_none", tuple(sorted(missions)) if missions else None)
    if key in _CACHE:
        r = _CACHE[key]
        return r.dir if r else None
    try:
        r = resolve_missions_dir(missions=missions, quiet=True)
    except StockDataError:
        r = None
    _CACHE[key] = r
    return r.dir if r else None


def _explicit_failure_text(d: Path, bad: list[str]) -> str:
    head = "\n".join(f"    {b}" for b in bad[:12])
    more = f"\n    ... and {len(bad) - 12} more" if len(bad) > 12 else ""
    return (f"--missions-dir {d} is NOT the stock mission data the engine ships.\n"
            f"  {len(bad)} file(s) disagree with the shipped mission.fst:\n"
            f"{head}{more}\n"
            f"  Analysis of this data does NOT describe stock terrain.\n"
            f"  Pass --allow-nonstock if that is deliberate (modded/custom map), "
            f"or drop --missions-dir to let the resolver find verified data.")


def _shout(res: Resolved) -> None:
    bar = "!" * 78
    print(f"\n{bar}\n{res.banner()}", file=sys.stderr)
    for b in res.mismatches[:8]:
        print(f"    {b}", file=sys.stderr)
    if len(res.mismatches) > 8:
        print(f"    ... and {len(res.mismatches) - 8} more", file=sys.stderr)
    print("  proceeding because --allow-nonstock was given.\n"
          f"{bar}\n", file=sys.stderr)


