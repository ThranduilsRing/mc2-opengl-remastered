_FST_ENTRY = struct.Struct("<IIII250s")


class StockDataError(RuntimeError):
    """Raised when stock mission data cannot be located or cannot be proven.

    Callers should let this propagate. Swallowing it and continuing on
    whatever directory happened to be around is precisely the defect this
    module exists to make impossible.
    """


@dataclass
class Resolved:
    """A mission-data directory plus the evidence that it is the shipped one."""

    dir: Path
    label: str
    verified: bool
    checked: int = 0
    stems: tuple[str, ...] = ()
    note: str = ""
    mismatches: tuple[str, ...] = field(default=())

    def banner(self) -> str:
        if self.verified:
            return (f"[stock-missions] {self.dir}  ({self.label}; "
                    f"{self.checked} file(s) match the shipped mission.fst)")
        return (f"[stock-missions] !! UNVERIFIED !! {self.dir}  ({self.label}; "
                f"{len(self.mismatches)} file(s) differ from the shipped "
                f"mission.fst) -- results do NOT describe stock terrain")


