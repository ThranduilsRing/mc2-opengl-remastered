#!/usr/bin/env python3
"""What: builds docs/split-map.md, the map from each split source file to the pieces it became, one line per piece saying what it holds.
Why: after a file-size split the old file name no longer says where its code went. The map is derived from tools/split/allow/*.json (src, stem)
and from the pieces themselves (the first comment line of each <stem>_*.cpp, the banner of each <stem>_*internal.h), so it cannot drift from the tree:
--check fails when a piece appears, disappears or changes its description without the map being regenerated.
Usage: py -3 tools/split/split_map.py --write    (regenerate docs/split-map.md)
       py -3 tools/split/split_map.py --check    (exit 1 when docs/split-map.md is stale; wired into scripts/check-contracts.sh as split_map)
Line counts are left out on purpose: comment-only passes change them and would turn the check red for no reason."""
import argparse, glob, json, os, re, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
ALLOW = os.path.join(REPO, "tools", "split", "allow", "*.json")
OUT = os.path.join(REPO, "docs", "split-map.md")


def ascii_clean(s):
    return "".join(c if ord(c) < 128 else "-" for c in s)


def read_lines(path):
    with open(path, "rb") as fh:
        return [ascii_clean(l.decode("utf-8", "replace").rstrip("\r")) for l in fh.read().split(b"\n")]


def first_comment(path):
    """Description of a piece: its first real comment line (a wrapped second line is joined when the first has no full stop)."""
    lines = read_lines(path)
    for i, l in enumerate(lines[:12]):
        t = l.strip()
        if not t.startswith("//"):
            continue
        body = t[2:].strip()
        if not body or set(body) <= set("=-*/ "):
            continue
        if not body.endswith(".") and i + 1 < len(lines) and lines[i + 1].strip().startswith("//"):
            nxt = lines[i + 1].strip()[2:].strip()
            if nxt and not set(nxt) <= set("=-*/ ") and not nxt.lower().startswith(("declared in", "include ")):
                body = body + " " + nxt
        return body
    return "(no description comment)"


def core_description(headers, src_base):
    """What the original file kept: the sentence of the shared header's banner that starts with '<file> keeps'."""
    for h in headers:
        lines = read_lines(h)
        for i, l in enumerate(lines[:14]):
            t = l.strip()
            if t.startswith("//") and (" keeps " in t or t.startswith("// " + src_base + " keeps")):
                out = [t[2:].strip()]
                for l2 in lines[i + 1:i + 5]:
                    t2 = l2.strip()
                    if not t2.startswith("//") or not t2[2:].strip():
                        break
                    out.append(t2[2:].strip())
                    if t2.endswith("."):
                        break
                text = " ".join(out)
                m = re.search(r"keeps (.*?)(?:;|\. |$)", text)
                if m:
                    return "keeps " + m.group(1).rstrip(".")
    return "keeps what the pieces below did not take"


def build():
    groups = {}
    for f in sorted(glob.glob(ALLOW)):
        with open(f, encoding="utf-8") as fh:
            d = json.load(fh)
        src, stem = d.get("src"), d.get("stem")
        if not src or not stem:
            continue
        g = groups.setdefault(src, {"stems": set(), "commits": [], "pieces": set(), "headers": set()})
        g["stems"].add(stem)
        skip = set(d.get("exclude_files", []))
        base_dir = os.path.join(REPO, os.path.dirname(src))
        for p in glob.glob(os.path.join(base_dir, stem + "_*.cpp")):
            if os.path.basename(p) not in skip:
                g["pieces"].add(os.path.basename(p))
        for p in glob.glob(os.path.join(base_dir, stem + "_*internal.h")):
            if os.path.basename(p) not in skip:
                g["headers"].add(os.path.basename(p))
        if d.get("split_commit") and d["split_commit"] != "PENDING":
            g["commits"].append(d["split_commit"])
    out = ["# Split map", "",
           "Generated by `tools/split/split_map.py --write` from `tools/split/allow/*.json` and the pieces' own header comments; "
           "`--check` (the `split_map` contract row) fails when it is stale. Each oversized source file was cut into the pieces below "
           "by moving whole top-level units verbatim; the shared declarations of every split live in the `*_internal.h` header listed with it.", ""]
    for src in sorted(groups):
        g = groups[src]
        d = os.path.dirname(src)
        base = os.path.basename(src)
        pieces, headers = g["pieces"], g["headers"]
        hdr_paths = [os.path.join(REPO, d, h) for h in sorted(headers)]
        # a removed original is named without backticks so doc_links does not read it as a live path
        out.append("## `%s`" % src if os.path.exists(os.path.join(REPO, src)) else "## %s (original removed)" % src)
        out.append("")
        if g["commits"]:
            out.append("Split commit%s: %s." % ("s" if len(g["commits"]) > 1 else "", ", ".join("`%s`" % c for c in g["commits"])))
            out.append("")
        out.append("| Piece | What it holds |")
        out.append("|---|---|")
        if os.path.exists(os.path.join(REPO, src)):
            out.append("| `%s` | %s |" % (base, core_description(hdr_paths, base)))
        for p in sorted(pieces):
            out.append("| `%s` | %s |" % (p, first_comment(os.path.join(REPO, d, p)).replace("|", "/")))
        for h in sorted(headers):
            out.append("| `%s` | shared include bundle, extern globals and declarations of the pieces |" % h)
        out.append("")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.write:
        with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("split_map: wrote %s (%d source files)" % (os.path.basename(OUT), text.count("\n## ")))
        return 0
    try:
        with open(OUT, encoding="utf-8", newline="") as fh:
            have = fh.read().replace("\r\n", "\n")
    except FileNotFoundError:
        have = ""
    if have != text:
        print("split_map: FAIL - docs/split-map.md is stale (a split piece was added, removed or re-described); run: py -3 tools/split/split_map.py --write")
        import difflib
        for l in list(difflib.unified_diff(have.split("\n"), text.split("\n"), "docs/split-map.md", "generated", lineterm="", n=0))[:12]:
            print("  " + l)
        return 1
    print("split_map: OK")
    return 0


if __name__ == "__main__":
    sys.exit(main())
