#!/usr/bin/env python3
"""gate_table_gen -- the table half of tools/gate_gen.py (typed gate registry).

WHAT IT OWNS
------------
  Gates/gate_table.cpp    the hand-edited constexpr table; the single source.
  Gates/gate_table.json   emitted by the compiler (tools/gate_dump), committed. Everything below is derived
                          from THIS, so no Python regex ever parses the C++ table.
  Gates/gate_index.gen.h  generated {name, kind, rule, tokens} index the hot header reads.
  The registry rows of RenderCore/RendererFeatureRegistry.h and docs/flags.auto.yaml: tools/gate_registry_gen.py.

MODES (called from gate_gen.py)
-------------------------------
  --write          JSON -> index, registry rows, yaml
  --sync-verified  mark rows `verified` iff a typed reader exists, rebuild gate_dump, rewrite the JSON, --write
  --check          stage A (hermetic): JSON well formed and sorted, derived files current, every seed gate
                   still in the table, registry defaults agree, `verified` matches the typed readers, the
                   per-site rule-override count did not rise. --rebuild adds stage B: rebuild tools/gate_dump
                   and diff its JSON against the committed one (default/doc/owner drift the compiler cannot
                   see in the index).
"""

