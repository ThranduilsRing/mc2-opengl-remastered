def write_index(root):
    doc = _load_json(root, TABLE_JSON_REL)
    if doc is None:
        print("gate_table_gen: %s is missing: build tools/gate_dump and commit its output" % TABLE_JSON_REL)
        return 1
    rows = rows_from_json(doc)
    _write(root, INDEX_REL, render_index(rows))
    print("gate_table_gen: wrote %s from %s (%d gates)" % (INDEX_REL, TABLE_JSON_REL, len(rows)))
    import gate_registry_gen as grg
    print("gate_table_gen: wrote %s" % ", ".join(grg.write_all(root, doc)))
    return 0


def count_overrides(root):
    """Per-site rule overrides: gate::get<"MC2_X", gate::Rule::...>() outside Gates/ and tests."""
    pat = re.compile(r'get\s*<\s*"MC2_\w+"\s*,\s*[A-Za-z_]')   # a second template argument that is a Rule name
    n = 0
    for top in ("code", "mclib", "GameOS", "RenderCore", "GuiRuntime", "RenderWorld", "GameAdapters",
                "HostServices", "EditorBridge", "editor", "gui"):
        base = os.path.join(root, top)
        for dp, _dn, fns in os.walk(base):
            for fn in fns:
                if fn.endswith((".cpp", ".h", ".hpp", ".inl", ".cc")):
                    try:
                        with open(os.path.join(dp, fn), "r", encoding="utf-8", errors="replace") as fh:
                            n += len(pat.findall(fh.read()))
                    except OSError:
                        pass
    return n


READER_DIRS = ("code", "mclib", "GameOS", "RenderCore", "GuiRuntime", "RenderWorld", "GameAdapters", "HostServices",
               "EditorBridge", "editor", "gui", "tools")
_READER_RE = re.compile(r'(?<![A-Za-z_])(?:get|state|isSet|armed|regionTier1Armed|str|is)\s*<\s*"(MC2_\w+)"')


def typed_readers(root):
    """Names read through gate::get/state/isSet/str/is outside Gates/ and the tests (comments skipped)."""
    names = set()
    for top in READER_DIRS:
        for dp, dn, fns in os.walk(os.path.join(root, top)):
            dn[:] = [d for d in dn if d not in ("build", ".vs", "__pycache__")]
            for fn in fns:
                if not fn.endswith((".cpp", ".h", ".hpp", ".inl", ".cc")):
                    continue
                try:
                    with open(os.path.join(dp, fn), "r", encoding="utf-8", errors="replace") as fh:
                        for line in fh:
                            code = line.split("//", 1)[0]
                            names.update(_READER_RE.findall(code))
                except OSError:
                    pass
    return names


def _top_level_args(call):
    """Number of top-level arguments of `X(a, b, ...` (the closing paren is not in `call`); quotes and
    nested parentheses are skipped."""
    depth, n, i, in_str = 0, 1, call.index("(") + 1, False
    while i < len(call):
        c = call[i]
        if in_str:
            if c == "\\":
                i += 1
            elif c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == "," and depth == 0:
            n += 1
        i += 1
    return n


def sync_verified(root, outdir=None):
    """Mark rows `verified` iff a typed reader exists, rebuild gate_dump, rewrite Gates/gate_table.json and the
    index. One command after a migration."""
    import tempfile
    readers = typed_readers(root)
    tp = os.path.join(root, TABLE_CPP_REL.replace("/", os.sep))
    with open(tp, "r", encoding="utf-8", newline="") as fh:
        text = fh.read()
    nl = "\r\n" if "\r\n" in text else "\n"
    out, changed = [], 0
    for line in text.split(nl):
        m = re.match(r'^[GLP]\((?:[A-Za-z0-9]+, )?"(MC2_\w+)"', line)
        if m:
            has = re.search(r'(?:, | \| )verified(?= \||\))', line) is not None
            want = m.group(1) in readers
            if want and not has:
                mm = re.match(r'^(.*)\)(,\s*(?://.*)?)$', line)
                body, tail = mm.group(1), mm.group(2)
                has_opts = _top_level_args(body) > (7 if line.startswith("L(") else 6)
                line = body + ((" | verified)" if has_opts else ", verified)")) + tail
                changed += 1
            elif has and not want:
                line = re.sub(r' \| verified(?= \||\))', '', line)
                line = re.sub(r', verified\)', ')', line)
                changed += 1
        out.append(line)
    if changed:
        with open(tp, "w", encoding="utf-8", newline="") as fh:
            fh.write(nl.join(out))
    with tempfile.TemporaryDirectory(prefix="gate_dump_") as td:
        exe = build_gate_dump(root, td)
        if exe is None:
            print("gate_table_gen: tools/gate_dump did not build")
            return 1
        r = subprocess.run([exe], capture_output=True, text=True, **nofocus.hidden_kwargs())
        if r.returncode != 0:
            print("gate_table_gen: gate_dump exited %d" % r.returncode)
            return 1
        _write(root, TABLE_JSON_REL, r.stdout.replace("\r\n", "\n"))
    write_index(root)
    print("gate_table_gen: %d row(s) re-marked; %d typed reader name(s)" % (changed, len(readers)))
    return 0


def persistent_build_dir(root):
    """Keep the incremental check build inside its worktree, including linked checkouts.

    A linked checkout's git metadata can be outside the lane's writable root.
    Use ignored scratch instead; fall back to temp if the worktree is read-only.
    """
    import tempfile
    p = os.path.join(os.path.abspath(root), "scratch", "gate-dump-check")
    try:
        os.makedirs(p, exist_ok=True)
        return p
    except OSError:
        return tempfile.mkdtemp(prefix="gate_dump_")


def build_gate_dump(root, outdir):
    """Configure and build tools/gate_dump into `outdir`; return the exe path or None."""
    src = os.path.join(root, "tools", "gate_dump")
    if not os.path.isfile(os.path.join(src, "CMakeLists.txt")):
        print("gate_table_gen: tools/gate_dump/CMakeLists.txt is missing")
        return None
    vs = ("C:/Program Files (x86)/Microsoft Visual Studio/2022/BuildTools/Common7/IDE/CommonExtensions/"
          "Microsoft/CMake/CMake/bin/cmake.exe")
    cm = vs if os.path.isfile(vs) else "cmake"
    r = subprocess.run([cm, "-S", src, "-B", outdir, "-A", "x64"], capture_output=True, text=True,
                       **nofocus.hidden_kwargs())
    if r.returncode != 0:
        print((r.stdout + r.stderr)[-2000:])
        return None
    r = subprocess.run([cm, "--build", outdir, "--config", "RelWithDebInfo", "--parallel", "2"], capture_output=True, text=True,
                       **nofocus.hidden_kwargs())
    if r.returncode != 0:
        print((r.stdout + r.stderr)[-4000:])
        return None
    for cand in (os.path.join("RelWithDebInfo", "gate_dump.exe"), "gate_dump.exe", "gate_dump"):
        p = os.path.join(outdir, cand)
        if os.path.isfile(p):
            return p
    return None


def check(root, rebuild=False):
    fails = []
    doc = _load_json(root, TABLE_JSON_REL)
    if doc is None:
        return ["%s is missing: build tools/gate_dump and commit its output" % TABLE_JSON_REL]
    rows = rows_from_json(doc)
    names = [r["name"] for r in rows]
    if names != sorted(names) or len(set(names)) != len(names):
        fails.append("%s is not sorted/unique" % TABLE_JSON_REL)
    if doc.get("count") != len(rows):
        fails.append("%s count field %s != %d rows" % (TABLE_JSON_REL, doc.get("count"), len(rows)))
    import gate_registry_gen as grg
    fails.extend(grg.check_all(root, doc))
    ip = os.path.join(root, INDEX_REL.replace("/", os.sep))
    have = open(ip, "r", encoding="utf-8", newline="").read() if os.path.isfile(ip) else None
    if have != render_index(rows):
        fails.append("%s is stale against %s: run py -3 tools/gate_gen.py --write" % (INDEX_REL, TABLE_JSON_REL))
    seed = _load_json(root, SEED_REL)
    if seed is not None:
        retired = set(_load_json(root, "Gates/retired_names.json") or [])
        active_retired = sorted(retired & set(names))
        if active_retired:
            fails.append("retired gate(s) still in the live table: " + ", ".join(active_retired))
        missing = sorted(set(g["name"] for g in seed["gates"]) - set(names) - retired)
        if missing:
            fails.append("%d seed gate(s) are not in the table: %s" % (len(missing), ", ".join(missing[:6])))
    # a registered Bool gate's feature default must equal the row's own default, unless the seed notes a deliberate
    # disagreement (a kill-switch variable whose feature is on while the variable is unset)
    noted = {g["name"] for g in (seed or {}).get("gates", []) if g.get("defaultDisagreement") or g.get("conflict")}
    for r in rows:
        reg = r.get("registry")
        if reg and r["kind"] == "Bool" and r["name"] not in noted and bool(r["default"]) != bool(reg["defaultOn"]):
            fails.append("%s: row default %s but its registry entry says defaultOn=%s (no defaultDisagreement note)"
                         % (r["name"], r["default"], reg["defaultOn"]))
    readers = typed_readers(root)
    for r in rows:
        if r.get("verified") and r["name"] not in readers:
            fails.append("%s is marked verified but no gate::get<> reader exists: run py -3 tools/gate_gen.py --sync-verified"
                         % r["name"])
        if not r.get("verified") and r["name"] in readers:
            fails.append("%s has a gate::get<> reader but is not marked verified: run py -3 tools/gate_gen.py --sync-verified"
                         % r["name"])
    base = (_load_json(root, OVERRIDE_BASELINE_REL) or {}).get("count", 0)
    ov = count_overrides(root)
    if ov > base:
        fails.append("per-site rule overrides rose: %d (baseline %d)" % (ov, base))
    if rebuild and not fails:
        td = persistent_build_dir(root)
        exe = build_gate_dump(root, td)
        if exe is None:
            fails.append("tools/gate_dump did not build")
        else:
            r = subprocess.run([exe], capture_output=True, text=True, **nofocus.hidden_kwargs())
            want = open(os.path.join(root, TABLE_JSON_REL.replace("/", os.sep)), "r", encoding="utf-8",
                        newline="").read()
            if r.returncode != 0:
                fails.append("gate_dump exited %d" % r.returncode)
            elif r.stdout.replace("\r\n", "\n") != want.replace("\r\n", "\n"):
                fails.append("%s differs from what the compiled table emits: rebuild tools/gate_dump and commit "
                             "its output (default/doc/owner drift)" % TABLE_JSON_REL)
    return fails
