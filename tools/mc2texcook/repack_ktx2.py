#!/usr/bin/env python3
"""Lossless repack of uncompressed RGBA8 KTX2 files that `ktx validate` rejects.

  py -3 tools/mc2texcook/repack_ktx2.py DIR [--dry-run]

The data/textures/*.ktx2 sidecars are cook outputs that live only in installs (not in git,
not regenerated by deploy_payload). Run this once over each persistent install's data dir
(v0.4, owner installs) to fix the ones written by the old mc2texcook writer (bad DFD,
stray kvd offset, largest-first levels). Pixels are untouched. Files are replaced by
unlink + write, so a hardlinked copy in another install is not modified. Idempotent.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools" / "mc2texcook"))
from tools.content_pipeline import texcook  # noqa: E402
import check_ktx2_valid  # noqa: E402


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("dir")
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()
    ktx = check_ktx2_valid.find_ktx()
    if not ktx:
        print("FAIL repack_ktx2: " + check_ktx2_valid.INSTALL_HELP)
        return 1
    fixed = skipped = 0
    for f in sorted(Path(args.dir).rglob("*.ktx2")):
        if "_aoktxtmp" in f.parts:
            continue
        if subprocess.run([ktx, "validate", str(f)], capture_output=True).returncode == 0:
            continue
        try:
            vk, w, h, levels = texcook.read_ktx2(f.read_bytes())
            if vk not in (texcook.VK_RGBA8_UNORM, texcook.VK_RGBA8_SRGB):
                raise ValueError(f"vkFormat {vk} is not uncompressed RGBA8")
            data = texcook.write_ktx2(vk, w, h, levels)
        except Exception as e:  # leave the file alone, report it
            print(f"SKIP {f}: {e}")
            skipped += 1
            continue
        if not args.dry_run:
            f.unlink()
            f.write_bytes(data)
        fixed += 1
    print(f"repack_ktx2: fixed {fixed}, skipped {skipped}{' (dry run)' if args.dry_run else ''}")
    return 1 if skipped else 0


if __name__ == "__main__":
    sys.exit(main())
